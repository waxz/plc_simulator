"""
ax_export.py - the layout's PLC exchange as SIMATIC AX ST: the one generator
of it. The designer (File > Export to SIMATIC AX), st_export.py (command
line) and the AX project's tools/generate_st_serde.py --sim-config all write
the ST through this module, from the exchange contract (st_export.contract)
- so the STRUCTs, serializers and constants are defined once, here.

One .st file per export (AxExport settings, saved in the layout):

  the device STRUCTs and one STRUCT per frame (Sim_Input, Sim_Output, ...;
  --prefix Station_1 names them Station_1_Input / ...); a laser banner's
  beams as one BYTE / WORD / DWORD / LWORD (bitArrays keeps ARRAY OF BOOL)
  DeserializeFromBytes / SerializeToBytes per frame, at the contract's byte
  / bit offsets, each first checking the buffer is long enough
  the PLC tags (Sim_Tags) and ReadTags / WriteTags (tags)
  CLASS SimIoContract: frame types, sizes, layout fingerprints

and optionally an AxUnit golden-vector test (vectors): sample values must
serialize to exactly the bytes the simulator's packer makes, and back.
A frame bigger than the AX TcpClient's buffer (maxPayload) is refused.
"""
from __future__ import annotations

import os
import re
import struct
from dataclasses import dataclass
from typing import Optional


class ExportError(ValueError):
    """The layout can't be exported as asked (the message says why)."""


CONTRACT_BYTE_TYPES = {"bit": "BOOL", "byte": "BYTE", "uint16": "UINT", "uint32": "UDINT",
                       "uint64": "ULINT", "float": "REAL"}
CONTRACT_BYTE_SIZES = {"bit": 1, "byte": 1, "uint16": 2, "uint32": 4, "uint64": 8, "float": 4}



def emit_length_guard(function: str, buffer: str, size: int) -> list[str]:
    """The first statements of a generated (de)serializer: a buffer too short
    for `size` bytes from startOffset is not touched - the function returns
    startOffset (nothing read / written), which the caller can tell from
    startOffset + size."""
    return [f"    IF UPPER_BOUND({buffer}, 1) - LOWER_BOUND({buffer}, 1) + DINT#1 < TO_DINT(startOffset) + DINT#{size} THEN",
            f"        {function} := startOffset;          // too short: nothing done",
            "        RETURN;",
            "    END_IF;"]



def prefix_renames(contract: dict, prefix: str | None) -> dict[str, str]:
    """--prefix Station_1: Sim_Input -> Station_1_Input, Sim_Output ->
    Station_1_Output (the frames named Sim_*; the others keep their names)."""
    if not prefix:
        return {}
    return {frame["name"]: prefix + frame["name"][len("Sim"):]
            for frame in contract["frames"] if frame["name"].startswith("Sim_")}


def contract_frames(contract: dict, only: list[str] | None) -> list[dict]:
    frames = contract["frames"]
    if only:
        names = {frame["name"] for frame in frames}
        unknown = [name for name in only if name not in names]
        if unknown:
            raise ExportError(f"--frames: {', '.join(unknown)} not in the contract "
                             f"(it has {', '.join(sorted(names))})")
        frames = [frame for frame in frames if frame["name"] in only]
    for frame in frames:
        if "members" not in frame:
            raise ExportError("the contract has no frame members: regenerate it with a current st_export.py")
    return frames


def emit_sim_header(contract: dict) -> list[str]:
    return [
        "// -----------------------------------------------------------------------------",
        "// <auto-generated>",
        f"// Generated by the conveyor simulator (ax_export.py) from the layout "
        f"{contract.get('source') or '(unnamed)'}",
        f"// (exchange contract {contract['fingerprint']:08X}). Do not edit by hand: regenerate.",
        "// -----------------------------------------------------------------------------",
    ]


def emit_sim_types(frames: list[dict], contract: dict, renames: dict[str, str]) -> list[str]:
    """The device STRUCTs the chosen frames use, then one STRUCT per frame."""
    used = {member["type"] for frame in frames for member in frame["members"]}
    lines = ["TYPE"]
    for type_name, fields in sorted(contract.get("structs", {}).items()):
        if type_name not in used:
            continue
        lines.append(f"    {type_name} : STRUCT")
        lines += [f"        {field['name']} : {field['type']};" for field in fields]
        lines.append("    END_STRUCT;")
    for frame in frames:
        lines.append(f"    // frame type {frame['frameType']}, {frame['size']} bytes, "
                     f"layout fingerprint {frame['fingerprint']:08X}")
        lines.append(f"    {renames.get(frame['name'], frame['name'])} : STRUCT")
        for member in frame["members"]:
            st_type = member["type"]
            if member.get("length"):
                st_type = f"ARRAY[0..{member['length'] - 1}] OF {st_type}"
            lines.append(f"        {member['name']} : {st_type};")
        lines.append("    END_STRUCT;")
    lines.append("END_TYPE")
    return lines


def emit_sim_serde(frame: dict, struct_name: str, endianness: str) -> list[str]:
    """DeserializeFromBytes / SerializeToBytes for one frame STRUCT, at the
    contract's byte / bit offsets (relative to startOffset)."""
    fields = frame["fields"]
    bit_bytes = sorted({field["byte"] for field in fields if field["type"] == "bit"})
    layout = ["// Byte mapping, relative to startOffset:"]
    for field in fields:
        if field["type"] == "bit":
            layout.append(f"//   {field['member']} -> byte {field['byte']}, bit {field['bit']}")
        else:
            last = field["byte"] + CONTRACT_BYTE_SIZES[field["type"]] - 1
            where = f"byte {field['byte']}" if last == field["byte"] else f"bytes {field['byte']}..{last}"
            layout.append(f"//   {field['member']} -> {where}")
    layout.append(f"// Total serialized size: {frame['size']} byte(s)")

    lines: list[str] = []
    for direction in ("Deserialize", "Serialize"):
        function = "DeserializeFromBytes" if direction == "Deserialize" else "SerializeToBytes"
        buffer = "source" if direction == "Deserialize" else "dest"
        lines += [f"// {struct_name}: {direction.lower()}", *layout,
                  f"FUNCTION {function} : UDINT",
                  "    VAR_INPUT",
                  "        startOffset : UDINT := UDINT#0;",
                  "    END_VAR",
                  "    VAR_IN_OUT"]
        if direction == "Deserialize":
            lines += ["        source : ARRAY[*] OF BYTE;", f"        value : {struct_name};"]
        else:
            lines += [f"        value : {struct_name};", "        dest : ARRAY[*] OF BYTE;"]
        lines += ["    END_VAR",
                  "    VAR_TEMP",
                  "        offset : UDINT;",
                  "        byteIdx : DINT;",
                  "    END_VAR",
                  "",
                  *emit_length_guard(function, buffer, frame["size"]),
                  f"    byteIdx := LOWER_BOUND({buffer}, 1) + TO_DINT(startOffset);"]
        if direction == "Serialize":
            lines += [f"    dest[byteIdx + DINT#{byte}] := BYTE#16#00;" for byte in bit_bytes]
        for field in fields:
            at = f"byteIdx + DINT#{field['byte']}"
            expr = f"value.{field['member']}"
            if field["type"] == "bit":
                if direction == "Deserialize":
                    lines.append(f"    {expr} := GetBit(source[{at}], USINT#{field['bit']});")
                else:
                    lines.append(f"    dest[{at}] := SetBit(value := dest[{at}], "
                                 f"index := USINT#{field['bit']}, bitValue := {expr});")
            elif direction == "Deserialize":
                lines.append(f"    offset := Deserialize(startOffset + UDINT#{field['byte']}, source, {expr}, "
                             f"{endianness});")
            else:
                lines.append(f"    offset := Serialize(startOffset + UDINT#{field['byte']}, {expr}, dest, "
                             f"{endianness});")
        lines += [f"    {function} := startOffset + UDINT#{frame['size']};", "END_FUNCTION", ""]
    return lines


def emit_sim_contract_class(frames: list[dict], contract: dict, class_name: str,
                            renames: dict[str, str]) -> list[str]:
    """The exchange's constants: frame types, frame sizes, fingerprints."""
    def constant(name: str) -> str:
        return re.sub(r"[^A-Za-z0-9_]", "_", name).upper()

    lines = [f"CLASS PUBLIC {class_name}",
             "    VAR CONSTANT PUBLIC",
             f"        CONTRACT_FINGERPRINT : DWORD := DWORD#16#{contract['fingerprint']:08X};"]
    for name, value in contract["frameTypes"].items():
        lines.append(f"        FRAME_TYPE_{constant(name)} : BYTE := BYTE#{value};")
    for frame in frames:
        name = constant(renames.get(frame["name"], frame["name"]))
        lines.append(f"        {name}_SIZE : UDINT := UDINT#{frame['size']};")
        lines.append(f"        {name}_FINGERPRINT : DWORD := DWORD#16#{frame['fingerprint']:08X};")
    lines += ["    END_VAR", "END_CLASS"]
    return lines


def tags_struct_name(renames: dict[str, str]) -> str:
    """Sim_Tags, or <prefix>_Tags with --prefix (as Sim_Input -> <prefix>_Input)."""
    renamed = renames.get("Sim_Input") or renames.get("Sim_Output")
    return renamed.rsplit("_", 1)[0] + "_Tags" if renamed else "Sim_Tags"


def member_type(frame: dict, contract: dict, member: str) -> str:
    """The ST type of a frame member ("div_1.present", "sensor_1_2_1") as
    the generated STRUCTs declare it."""
    top, _sep, field = member.partition(".")
    declared = next((m for m in frame["members"] if m["name"] == top), None)
    if declared is None:
        raise ExportError(f"tag member {frame['name']}.{member} is not in the frame: regenerate with a matching "
                         f"simulator")
    if field:
        return next(f["type"] for f in contract["structs"][declared["type"]] if f["name"] == field)
    if declared.get("length"):
        return f"ARRAY[0..{declared['length'] - 1}] OF {declared['type']}"
    return declared["type"]


def emit_sim_tags(frames: list[dict], contract: dict, tags: list, renames: dict[str, str]) -> list[str]:
    """The PLC tags (the designer's PLC Tags table) as ST: one STRUCT with a
    variable per tag, named as the tag (its ST name), grouped by tag table,
    the address and comment beside it; ReadTags copies an input frame into
    it (call it after that frame's DeserializeFromBytes), WriteTags copies
    it into the output frame (call it before SerializeToBytes)."""
    by_frame = {frame["name"]: frame for frame in frames}
    tags = [t for t in tags if t["frame"] in by_frame]
    if not tags:
        return []
    struct_name = tags_struct_name(renames)
    tables = sorted({t["table"] for t in tags}, key=lambda name: (name != "Default tag table", name.lower()))
    lines = ["TYPE",
             "    // The PLC tags (the designer's PLC Tags table): a variable per tag, named as the tag.",
             f"    {struct_name} : STRUCT"]
    for table in tables:
        lines.append(f"        // {table}")
        for t in (t for t in tags if t["table"] == table):
            comment = " ".join(f"{t['address']} {t['comment']}".split())
            if t["stName"] != t["name"]:
                comment += f" (tag \"{t['name']}\")"
            lines.append(f"        {t['stName']} : {member_type(by_frame[t['frame']], contract, t['member'])};"
                         f" // {comment}")
    lines += ["    END_STRUCT;", "END_TYPE", ""]
    for frame in frames:
        frame_tags = [t for t in tags if t["frame"] == frame["name"]]
        if not frame_tags:
            continue
        frame_struct = renames.get(frame["name"], frame["name"])
        if frame_tags[0]["input"]:
            lines += [f"// {frame_struct} -> {struct_name}: call after its DeserializeFromBytes.",
                      "FUNCTION ReadTags",
                      "    VAR_IN_OUT",
                      f"        source : {frame_struct};",
                      f"        tags : {struct_name};",
                      "    END_VAR",
                      "",
                      *[f"    tags.{t['stName']} := source.{t['member']};" for t in frame_tags]]
        else:
            lines += [f"// {struct_name} -> {frame_struct}: call before its SerializeToBytes.",
                      "FUNCTION WriteTags",
                      "    VAR_IN_OUT",
                      f"        tags : {struct_name};",
                      f"        dest : {frame_struct};",
                      "    END_VAR",
                      "",
                      *[f"    dest.{t['member']} := tags.{t['stName']};" for t in frame_tags]]
        lines += ["END_FUNCTION", ""]
    return lines


# A BOOL array of 8 / 16 / 32 / 64 bits that starts on a byte boundary and
# runs on contiguously (a laser banner's beams) is, in a little-endian frame,
# bit for bit a BYTE / WORD / DWORD / LWORD: bit i of the word is element i.
BIT_WORDS = {8: ("BYTE", "byte"), 16: ("WORD", "uint16"), 32: ("DWORD", "uint32"), 64: ("LWORD", "uint64")}


def pack_bit_arrays(frame: dict, endianness: str) -> dict:
    """The frame with each such BOOL array as one word member, read and
    written with a single Deserialize / Serialize instead of a GetBit /
    SetBit per bit. Big-endian frames keep their arrays (the bytes of a
    big-endian word run the other way)."""
    if endianness != "LE":
        return frame
    members, fields = [dict(m) for m in frame["members"]], list(frame["fields"])
    for member in members:
        length = member.get("length")
        if member["type"] != "BOOL" or length not in BIT_WORDS:
            continue
        name = member["name"]
        bits = {f["member"]: f for f in fields if f["type"] == "bit" and f["member"].startswith(name + "[")}
        first = bits.get(f"{name}[0]")
        if len(bits) != length or first is None or first["bit"] != 0:
            continue
        if any(bits.get(f"{name}[{i}]", {}).get("byte") != first["byte"] + i // 8
               or bits[f"{name}[{i}]"]["bit"] != i % 8 for i in range(length)):
            continue
        st_type, byte_type = BIT_WORDS[length]
        member["type"], member["length"] = st_type, None
        position = fields.index(first)
        word = {"byte": first["byte"], "bit": None, "type": byte_type, "path": first["path"], "member": name}
        fields = [f for f in fields if f["member"] not in bits]
        fields.insert(position, word)
    return {**frame, "members": members, "fields": fields}


# The SIMATIC AX TcpClient's send / receive buffers are 256 bytes: a frame
# (10 bytes header, the payload, 4 bytes trailer) carries 242 payload bytes at
# most (the simulator's mqtt_data_exchange.PLC_MAX_PAYLOAD).
PLC_MAX_PAYLOAD = 242


def check_frame_sizes(frames: list[dict], max_payload: int) -> None:
    """A frame bigger than the PLC's TCP buffer would never arrive whole:
    stop here, not at the PLC."""
    if not max_payload:
        return
    big = [f"{f['name']} ({f['size']} bytes)" for f in frames if f["size"] > max_payload]
    if big:
        raise ExportError(f"frame(s) larger than the PLC's {max_payload}-byte payload: {', '.join(big)}. "
                         "Split the layout into stations (--frames / several layouts), pack bits "
                         "(packFormat), or raise --max-payload if the PLC's buffers are bigger.")


def generate_from_contract(contract: dict, only: list[str] | None, renames: dict[str, str],
                           namespace: str | None, class_name: str, bit_arrays: bool = False,
                           tags: list | None = None, max_payload: int = PLC_MAX_PAYLOAD) -> str:
    frames = contract_frames(contract, only)
    check_frame_sizes(frames, max_payload)
    if not bit_arrays:
        frames = [pack_bit_arrays(frame, contract["endianness"]) for frame in frames]
    endianness = "Endianness#Little" if contract["endianness"] == "LE" else "Endianness#Big"
    body: list[str] = [*emit_sim_types(frames, contract, renames), ""]
    for frame in frames:
        body += emit_sim_serde(frame, renames.get(frame["name"], frame["name"]), endianness)
    if tags:
        body += emit_sim_tags(frames, contract, tags, renames)
    body += emit_sim_contract_class(frames, contract, class_name, renames)
    if namespace:
        body = [f"NAMESPACE {namespace}", "", *body, "", "END_NAMESPACE"]
    return "\n".join([*emit_sim_header(contract), "USING System.Serialization;", "USING System.BitAccess;",
                      "", *body, ""])




# -- golden vectors -------------------------------------------------------------------

_FMT = {"bit": "B", "byte": "B", "uint16": "H", "uint32": "I", "uint64": "Q", "float": "f"}


def _sample(field: dict, i: int):
    """Deterministic, exactly representable test values per field."""
    if field["type"] == "bit":
        return (i * 7 + 3) % 3 != 0
    if field["type"] == "float":
        return (i % 17) * 1.25 - 4.5
    if field["member"] == "clock":
        return 1_700_000_000_123_456_789 + i
    bits = CONTRACT_BYTE_SIZES[field["type"]] * 8
    return (i * 2654435761 + 97) % (1 << min(bits, 31))


def pack_frame(frame: dict, values: dict, endianness: str) -> bytes:
    """The frame's bytes for `values` (member -> value), as the simulator's
    packer lays them out (the contract's offsets)."""
    data = bytearray(frame["size"])
    order = "<" if endianness == "LE" else ">"
    for field in frame["fields"]:
        value = values[field["member"]]
        if field["type"] == "bit":
            if value:
                data[field["byte"]] |= 1 << field["bit"]
        else:
            fmt = "q" if field["member"] == "clock" else _FMT[field["type"]]
            struct.pack_into(order + fmt, data, field["byte"], value)
    return bytes(data)


def _declared(frame: dict, contract: dict, member: str) -> str:
    st_type = member_type(frame, contract, member.split("[")[0])
    return st_type.split(" OF ")[-1] if "[" in member else st_type


def _literal(value, st_type: str) -> str:
    if st_type == "BOOL":
        return "TRUE" if value else "FALSE"
    if st_type in ("REAL", "LREAL"):
        return f"{st_type}#{value!r}"
    return f"{st_type}#{value}"


def emit_vectors(frames: list[dict], contract: dict, renames: dict[str, str], namespace: str | None) -> str:
    """AxUnit tests: per frame, sample values serialize to exactly the
    simulator packer's bytes, and back."""
    space = namespace or "SimIo"
    lines = [*emit_sim_header(contract), "USING AxUnit.Assert;"] + ([f"USING {namespace};"] if namespace else [])
    lines += ["", f"NAMESPACE {space}.Tests", "    {TestFixture}", "    CLASS SimIoVectorsTest"]
    for frame in frames:
        name = renames.get(frame["name"], frame["name"])
        values = {f["member"]: _sample(f, i) for i, f in enumerate(frame["fields"])}
        expected = pack_frame(frame, values, contract["endianness"])
        size = frame["size"]
        lines += ["        {Test}",
                  f"        METHOD PUBLIC {name}_matches_the_simulator",
                  "            VAR_TEMP",
                  f"                value : {name};",
                  f"                back : {name};",
                  f"                bytes : ARRAY[0..{size - 1}] OF BYTE;",
                  f"                expected : ARRAY[0..{size - 1}] OF BYTE := "
                  f"[{', '.join(f'BYTE#16#{b:02X}' for b in expected)}];",
                  "                size : UDINT;",
                  "                i : DINT;",
                  "            END_VAR"]
        lines += [f"            value.{m} := {_literal(v, _declared(frame, contract, m))};" for m, v in values.items()]
        lines += ["            size := SerializeToBytes(UDINT#0, value, bytes);",
                  f"            Equal(actual := size, expected := UDINT#{size});",
                  f"            FOR i := 0 TO {size - 1} DO",
                  "                Equal(actual := bytes[i], expected := expected[i]);",
                  "            END_FOR;",
                  "            size := DeserializeFromBytes(UDINT#0, expected, back);",
                  f"            Equal(actual := size, expected := UDINT#{size});"]
        lines += [f"            Equal(actual := back.{m}, expected := value.{m});" for m in values]
        lines.append("        END_METHOD")
    lines += ["    END_CLASS", "END_NAMESPACE", ""]
    return "\n".join(lines)


# -- one export: the settings saved in the layout ---------------------------------------

@dataclass
class Export:
    """What one export wrote / would write: {path: text}, and a line per
    frame for the person who asked (sizes, the payload limit)."""
    files: dict
    report: list


def resolve(path: str, layout_path: Optional[str]) -> str:
    """A settings path: relative to the layout file's folder."""
    if not path or os.path.isabs(path) or not layout_path:
        return path
    return os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(layout_path)), path))


def export(contract: dict, settings, tags: list | None = None, layout_path: Optional[str] = None) -> Export:
    """The ST for `settings` (config_parser.AxExport): ExportError with the
    reason when it can't be made (no output file, an unknown frame, a frame
    too big for the PLC)."""
    if not settings.output:
        raise ExportError("No output file: choose where the .st file goes.")
    only = list(settings.frames) or None
    renames = prefix_renames(contract, settings.prefix or None)
    namespace = settings.namespace or None
    text = generate_from_contract(contract, only, renames, namespace, "SimIoContract", settings.bitArrays,
                                  tags if settings.tags else None, settings.maxPayload)
    files = {resolve(settings.output, layout_path): text}
    frames = contract_frames(contract, only)
    if not settings.bitArrays:
        frames = [pack_bit_arrays(f, contract["endianness"]) for f in frames]
    if settings.vectors:
        files[resolve(settings.vectors, layout_path)] = emit_vectors(frames, contract, renames, namespace)
    report = [f"{renames.get(f['name'], f['name'])}: {f['size']} bytes"
              + (f" of {settings.maxPayload}" if settings.maxPayload else "") for f in frames]
    return Export(files, report)


def write(result: Export, check: bool = False) -> list:
    """The files that differ from what is on disk; written unless `check`."""
    stale = []
    for path, text in result.files.items():
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read()
        except OSError:
            current = None
        if current != text:
            stale.append(path)
            if not check:
                os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
    return stale
