"""metric_layout.py - describe a metric frame's wire layout as a real
(nested) Python dataclass instead of a list of (ByteType, "group/name")
tuples.

The layout classes live in mqtt_data_exchange.py (hand-written for the
built-in layouts, generated by the web editor for new ones - see
mqtt_data_exchange_codegen.py). Each layout is a dataclass whose fields
are themselves dataclasses, one per metric *group*:

    @dataclass
    class Layout1Perf:
        scan_time_ms: f32
        sample_count: u32

    @dataclass
    class Layout1Results:
        last_result_code: u16
        belt_1_velocity: Vec2

    @dataclass
    class MetricLayout1:
        perf:    Layout1Perf
        results: Layout1Results

layout_mapping() turns that back into the exact
[(ByteType, "group/name" | "group/name[i]"), ...] list the wire engine
(MetricsMessage / create_pack_format_string / parse_path in
mqtt_message_binding.py) already consumes, so nothing downstream of the
declaration changes. layout_values() flattens a filled-in instance to the
{(group, name): value} dict MetricsMessage.serialize() already takes.

Field width comes from a typing.Annotated alias (a plain `float` is
unambiguous, a plain `int` is not):

    f32  - FLOAT     u8  - BYTE      bit  - BIT
    u16  - UINT16    u32 - UINT32    u64  - UINT64
    Vec2 - two FLOATs (packed as name[0], name[1])
    Vec3 - three FLOATs
"""
from dataclasses import fields, is_dataclass
from typing import Annotated, Any, Dict, List, Optional, Tuple, get_args, get_origin, get_type_hints

from mqtt_message_binding import ByteType

# --- width aliases -----------------------------------------------------
# The second Annotated arg is the wire ByteType; a vector alias wraps a
# fixed-length tuple whose element count becomes the number of name[i]
# slots the field expands to.
f32 = Annotated[float, ByteType.FLOAT]
u8 = Annotated[int, ByteType.BYTE]
u16 = Annotated[int, ByteType.UINT16]
u32 = Annotated[int, ByteType.UINT32]
u64 = Annotated[int, ByteType.UINT64]
bit = Annotated[bool, ByteType.BIT]
Vec2 = Annotated[Tuple[float, float], ByteType.FLOAT]
Vec3 = Annotated[Tuple[float, float, float], ByteType.FLOAT]

# Plain (un-aliased) annotations still resolve to something sensible.
_DEFAULT_BYTE_TYPE = {float: ByteType.FLOAT, bool: ByteType.BIT, int: ByteType.UINT32}

# ByteType -> the alias name codegen should emit for it (inverse of the
# aliases above), so a generated layout class reads f32/u16/... not
# Annotated[...] spelled out.
ALIAS_NAME = {
    ByteType.FLOAT: "f32",
    ByteType.BYTE: "u8",
    ByteType.UINT16: "u16",
    ByteType.UINT32: "u32",
    ByteType.UINT64: "u64",
    ByteType.BIT: "bit",
}
VECTOR_ALIAS = {2: "Vec2", 3: "Vec3"}


def _wire_spec(annotation: Any) -> Tuple[ByteType, Optional[int]]:
    """(ByteType, vector_length or None) for one field annotation."""
    metadata = getattr(annotation, "__metadata__", ())
    base = getattr(annotation, "__origin__", annotation) if metadata else annotation
    byte_type = next((m for m in metadata if isinstance(m, ByteType)), None)

    if get_origin(base) in (tuple, list):
        elems = [e for e in get_args(base) if e is not Ellipsis]
        return byte_type or ByteType.FLOAT, (len(elems) or None)

    return byte_type or _DEFAULT_BYTE_TYPE.get(base, ByteType.FLOAT), None


def _group_classes(layout_cls: type) -> List[Tuple[str, type]]:
    if not is_dataclass(layout_cls):
        raise TypeError(f"{layout_cls!r} is not a dataclass metric layout")
    hints = get_type_hints(layout_cls, include_extras=True)
    out: List[Tuple[str, type]] = []
    for f in fields(layout_cls):
        group_cls = hints.get(f.name, f.type)
        if not is_dataclass(group_cls):
            raise TypeError(
                f"metric layout {layout_cls.__name__}: field {f.name!r} must be a "
                f"dataclass (one per metric group), got {group_cls!r}"
            )
        out.append((f.name, group_cls))
    return out


def layout_mapping(layout_cls: type) -> List[Tuple[ByteType, str]]:
    """The (ByteType, path) list for a metric layout dataclass - the exact
    shape MetricsMessage already takes. A scalar field emits one
    'group/name' entry; a Vec2/Vec3 field emits 'group/name[0..n-1]'."""
    rows: List[Tuple[ByteType, str]] = []
    for group_name, group_cls in _group_classes(layout_cls):
        field_hints = get_type_hints(group_cls, include_extras=True)
        for f in fields(group_cls):
            byte_type, vector_len = _wire_spec(field_hints.get(f.name, f.type))
            if vector_len is None:
                rows.append((byte_type, f"{group_name}/{f.name}"))
            else:
                for i in range(vector_len):
                    rows.append((byte_type, f"{group_name}/{f.name}[{i}]"))
    return rows


def layout_values(instance: Any) -> Dict[Tuple[str, str], Any]:
    """Flatten a filled-in layout instance to the {(group, name): value}
    dict MetricsMessage.serialize() consumes. A vector field's value is
    passed through as-is (a list/tuple); serialize() indexes it."""
    if not is_dataclass(instance) or isinstance(instance, type):
        raise TypeError(f"expected a metric layout instance, got {instance!r}")
    out: Dict[Tuple[str, str], Any] = {}
    for group_field in fields(instance):
        group_obj = getattr(instance, group_field.name)
        for f in fields(group_obj):
            out[(group_field.name, f.name)] = getattr(group_obj, f.name)
    return out
