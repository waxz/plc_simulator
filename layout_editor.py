# Whether the simulation is currently playing - read by ButtonItem to decide
# whether a click presses the button (playing, mirrors editor_ui.py's
# `if self.playing: clicked_item.sensor_states = True`) or selects/drags it
# for editing (paused, normal PlacedItem behavior). A small bit of shared
# mutable state is the pragmatic choice here since ButtonItem instances are
# constructed in many places (config load, drag-drop, paste, duplicate)
# that don't have a MainWindow reference to thread a callback through
# individually, and there is only ever one simulation running per process.
_SIM_STATE = {"playing": False}


class ButtonItem(PlacedItem):
    """A momentary push-button. While the simulation is playing, pressing
    and holding it sets `model.sensor_states = True` (released -> False),
    matching editor_ui.py's ControlButton press behavior; while paused, it
    behaves like any other PlacedItem so it can be positioned/edited."""

    kind = "button"

    def __init__(self, model: ControlButton):
        super().__init__(model, self._local_points_for_model(model))
        self._pressed = False
        self._sync_brush()

    @staticmethod
    def _local_points_for_model(model: ControlButton) -> list[QPointF]:
        hw, hh = model.width * SCALE / 2.0, model.height * SCALE / 2.0
        return [QPointF(-hw, -hh), QPointF(hw, -hh), QPointF(hw, hh), QPointF(-hw, hh)]

    def set_size(self, width: float, height: float):
        self.model.width = width
        self.model.height = height
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF(self._local_points_for_model(self.model)))

    def _sync_brush(self):
        color = QColor(self.model.color)
        if self._pressed:
            color = color.darker(140)
        self.setBrush(QBrush(color))
        self.setPen(Qt.NoPen)

    def mousePressEvent(self, event):
        if _SIM_STATE["playing"] and event.button() == Qt.LeftButton:
            self._pressed = True
            self.model.sensor_states = True
            self._sync_brush()
            self.update()
            event.accept()
            return
        if not _SIM_STATE["playing"] and event.button() == Qt.LeftButton:
            label = self.model.label or self.model.id
            print(f"[Sim] '{label}' is selected for editing, not pressed - "
                  f"press Play to resume the simulation so button presses register.")
        super().mousePressEvent(event)

    def mouseReleaseEvent(self, event):
        if self._pressed:
            self._pressed = False
            self.model.sensor_states = False
            self._sync_brush()
            self.update()
            event.accept()
            return
        super().mouseReleaseEvent(event)

    def paint(self, painter: QPainter, option, widget=None):
        # Read `model.sensor_states` directly (not the local `_pressed`
        # flag) so the visual always reflects the actual state, the same
        # "source of truth, recomputed every repaint" approach SensorItem
        # uses - not just the mouse-driven case this prototype currently
        # exercises, but also state set any other way in the future (e.g.
        # an MQTT binding).
        pressed = bool(self.model.sensor_states)
        rect = self.polygon().boundingRect()
        if pressed:
            # Soft glow behind the button, echoing SensorItem's triggered-
            # outline treatment, so a press reads clearly at a glance even
            # with several buttons on screen.
            margin = max(rect.width(), rect.height()) * 0.25
            painter.setPen(Qt.NoPen)
            painter.setBrush(QBrush(QColor(255, 255, 0, 100)))
            painter.drawRect(rect.adjusted(-margin, -margin, margin, margin))
            self.setPen(QPen(QColor(255, 220, 0), 3))
        else:
            self.setPen(Qt.NoPen)
        super().paint(painter, option, widget)
        painter.setPen(QPen(Qt.white))
        painter.drawText(rect, Qt.AlignCenter, self.model.label)


class LedItem(PlacedItem):
    """An LED indicator, approximated as a many-sided regular polygon so it
    can share PlacedItem's polygon-based key-point/snap system - the same
    approach used for curved (arc) belts - rather than needing a separate
    QGraphicsEllipseItem code path. No `rotation` field in the schema
    (matches Sink)."""

    kind = "led"
    CIRCLE_SEGMENTS = 20

    def __init__(self, model: LedIndicator):
        super().__init__(model, self._local_points_for_model(model))
        self._sync_brush()

    @staticmethod
    def _local_points_for_model(model: LedIndicator) -> list[QPointF]:
        r = model.radius * SCALE
        points = []
        for i in range(LedItem.CIRCLE_SEGMENTS):
            angle = 2 * math.pi * i / LedItem.CIRCLE_SEGMENTS
            points.append(QPointF(r * math.cos(angle), -r * math.sin(angle)))
        return points

    def set_size(self, radius: float):
        self.model.radius = radius
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF(self._local_points_for_model(self.model)))

    def _sync_brush(self):
        base = QColor(self.model.color)
        self.setBrush(QBrush(base if self.model.isOn else base.darker(300)))
        self.setPen(Qt.NoPen)

    def _local_key_points(self):
        # The CIRCLE_SEGMENTS-sided polygon has 20 vertices + 20 edge
        # midpoints + center = 41 keypoints by PlacedItem's default -
        # meaningless as individual snap targets for a single round LED.
        # Reduce to the 4 cardinal points + center, the LED equivalent of
        # BeltItem's curved-belt corner reduction.
        r = self.model.radius * SCALE
        return [QPointF(r, 0), QPointF(0, -r), QPointF(-r, 0), QPointF(0, r), QPointF(0, 0)]

    def _local_edges(self):
        # A circle has no straight boundary segment to offer for
        # edge-to-edge alignment - unlike a curved belt's ring segment,
        # which has real straight radial edges at its start/end angles, an
        # LED's ring is fully closed with no such edge.
        return []

    def paint(self, painter: QPainter, option, widget=None):
        rect = self.polygon().boundingRect()
        if self.model.isOn:
            # A soft halo behind the LED, drawn before the LED face so it
            # reads as glowing/emitting rather than just "a brighter dot" -
            # `_sync_brush`'s flat fill-darkening alone was hard to tell
            # apart from a merely lighter color choice.
            glow = QColor(self.model.color)
            glow.setAlpha(110)
            extra = max(rect.width(), rect.height()) * 0.6
            painter.setPen(Qt.NoPen)
            painter.setBrush(QBrush(glow))
            painter.drawEllipse(rect.center(), rect.width() / 2.0 + extra, rect.height() / 2.0 + extra)
        super().paint(painter, option, widget)
        painter.setPen(QPen(Qt.white))
        label_rect = rect.adjusted(rect.width(), 0, rect.width() * 4, 0)
        painter.drawText(label_rect, Qt.AlignLeft | Qt.AlignVCenter, self.model.label)


class FreeDrawScene(QGraphicsScene):
    def __init__(self):
        super().__init__(-300, -300, 600, 600)
        self.setBackgroundBrush(QBrush(QColor(30, 30, 30)))

    def drawBackground(self, painter: QPainter, rect: QRectF):
        super().drawBackground(painter, rect)
        painter.setPen(QPen(QColor(55, 55, 55), 0))
        left = int(rect.left()) - (int(rect.left()) % GRID_SIZE)
        top = int(rect.top()) - (int(rect.top()) % GRID_SIZE)
        x = left
        while x < rect.right():
            painter.drawLine(x, rect.top(), x, rect.bottom())
            x += GRID_SIZE
        y = top
        while y < rect.bottom():
            painter.drawLine(rect.left(), y, rect.right(), y)
            y += GRID_SIZE
        painter.setPen(QPen(QColor(150, 60, 60), 0))
        painter.drawLine(0, rect.top(), 0, rect.bottom())
        painter.setPen(QPen(QColor(60, 150, 60), 0))
        painter.drawLine(rect.left(), 0, rect.right(), 0)


class ShapeDrawCanvas(QGraphicsView):
    """Canvas for the Shape Designer. Mouse behavior depends on `mode`:
      - "freehand": press-drag-release traces a continuous outline
        (decimated by on-screen segment length, closing near-duplicate
        trimmed on release).
      - "triangle"/"quadrilateral": click each vertex in turn; the shape
        auto-finishes after 3 or 4 clicks.
      - "arc": the center is always the fixed grid origin (the crosshair
        drawn by FreeDrawScene) - drag outward from anywhere to set radius
        and end angle in one gesture (start angle/thickness are numeric-
        only fields in the dialog - not practical to gesture precisely).
        Using a fixed origin instead of "wherever you first clicked" keeps
        the drag preview and the "Apply Parameters" preview centered at the
        exact same point, so the arc doesn't jump on release.
    `set_preview_points`/`set_preview_arc` let "Apply Parameters" show a
    shape built from typed numbers using the same preview path.
    """

    ORIGIN = QPointF(0, 0)
    MIN_SEGMENT_PX = 8.0
    VERTEX_COUNTS = {"triangle": 3, "quadrilateral": 4}

    def __init__(self):
        # QGraphicsView does not take ownership of its scene, so an
        # anonymous FreeDrawScene() passed straight into super().__init__()
        # has no surviving Python reference and gets garbage-collected
        # almost immediately, leaving self.scene() as None. Keep an
        # explicit attribute reference to keep it alive.
        self._owned_scene = FreeDrawScene()
        super().__init__(self._owned_scene)
        self.setRenderHint(QPainter.Antialiasing)
        # Same trailing-artifact fix as CanvasView: MinimalViewportUpdate
        # (the default) only repaints each changed item's own old+new
        # bounding box, which leaves faint grid remnants behind a moving/
        # resizing preview polygon (worst while dragging the arc preview).
        self.setViewportUpdateMode(QGraphicsView.FullViewportUpdate)
        self.mode = "freehand"
        self._drawing = False
        self.points: list[QPointF] = []
        self._preview_item = None
        self.on_shape_finished: Optional[Callable[[list], None]] = None
        self.on_arc_finished: Optional[Callable[[QPointF, QPointF], None]] = None

    def set_mode(self, mode: str):
        self.mode = mode
        self.reset()

    def reset(self):
        self._drawing = False
        self.points = []
        self._clear_preview()

    def set_preview_points(self, points: list[QPointF]):
        """Used by "Apply Parameters" to preview a shape built from typed
        numbers rather than a mouse gesture."""
        self.points = list(points)
        self._update_polygon_preview(self.points)

    def set_preview_arc(self, center: QPointF, radius_px: float, start_angle: float, end_angle: float, thickness_px: float):
        pts = arc_ring_points(radius_px, start_angle, end_angle, thickness_px)
        poly = QPolygonF([QPointF(center.x() + x, center.y() - y) for x, y in pts])
        self._set_preview_polygon(poly)

    def wheelEvent(self, event):
        factor = 1.15 if event.angleDelta().y() > 0 else 1 / 1.15
        self.scale(factor, factor)

    def mousePressEvent(self, event):
        if event.button() != Qt.LeftButton:
            super().mousePressEvent(event)
            return
        pos = self.mapToScene(event.pos())
        if self.mode == "freehand":
            self._drawing = True
            self.points = [pos]
            self._update_polygon_preview(self.points)
        elif self.mode in self.VERTEX_COUNTS:
            self.points.append(pos)
            self._update_polygon_preview(self.points)
            needed = self.VERTEX_COUNTS[self.mode]
            if len(self.points) >= needed:
                finished, self.points = self.points, []
                if self.on_shape_finished:
                    self.on_shape_finished(finished)
        elif self.mode == "arc":
            self._drawing = True
            self._preview_arc_drag(self.ORIGIN, pos)

    def mouseMoveEvent(self, event):
        pos = self.mapToScene(event.pos())
        if self.mode == "freehand" and self._drawing:
            last = self.points[-1]
            if (pos - last).manhattanLength() >= self.MIN_SEGMENT_PX:
                self.points.append(pos)
                self._update_polygon_preview(self.points)
        elif self.mode in self.VERTEX_COUNTS and self.points:
            self._update_polygon_preview(self.points + [pos])
        elif self.mode == "arc" and self._drawing:
            self._preview_arc_drag(self.ORIGIN, pos)
        else:
            super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        if event.button() != Qt.LeftButton:
            super().mouseReleaseEvent(event)
            return
        if self.mode == "freehand" and self._drawing:
            self._drawing = False
            points = self.points
            # A user closing the outline naturally brings the mouse back
            # near the starting point before releasing - drop that
            # near-duplicate trailing point so we don't store a degenerate
            # (near-zero-length) edge in the final polygon.
            if len(points) >= 2 and (points[-1] - points[0]).manhattanLength() < self.MIN_SEGMENT_PX * 1.5:
                points = points[:-1]
            self.points = points
            if len(points) >= 3 and self.on_shape_finished:
                self.on_shape_finished(points)
        elif self.mode == "arc" and self._drawing:
            self._drawing = False
            edge = self.mapToScene(event.pos())
            if (edge - self.ORIGIN).manhattanLength() >= self.MIN_SEGMENT_PX and self.on_arc_finished:
                self.on_arc_finished(self.ORIGIN, edge)
        # triangle/quadrilateral auto-finish inline in mousePressEvent.

    def _preview_arc_drag(self, center: QPointF, edge: QPointF):
        dx, dy = edge.x() - center.x(), edge.y() - center.y()
        radius_px = math.hypot(dx, dy)
        if radius_px < 1e-6:
            return
        end_angle = math.degrees(math.atan2(-dy, dx))
        if end_angle < 0:
            end_angle += 360.0
        self.set_preview_arc(center, radius_px, 0.0, end_angle, radius_px * 0.3)

    def _update_polygon_preview(self, points):
        if len(points) < 2:
            self._clear_preview()
            return
        self._set_preview_polygon(QPolygonF(points))

    def _set_preview_polygon(self, poly: QPolygonF):
        if self._preview_item is None:
            self._preview_item = self.scene().addPolygon(
                poly, QPen(QColor(59, 130, 246), 2), QBrush(QColor(59, 130, 246, 60))
            )
        else:
            self._preview_item.setPolygon(poly)

    def _clear_preview(self):
        if self._preview_item:
            self.scene().removeItem(self._preview_item)
            self._preview_item = None


