class ShapeDrawCanvas(QGraphicsView):
    """Canvas for the Shape Designer. Mouse behavior depends on `mode`:
      - "freehand": press-drag-release traces a continuous outline
        (decimated by on-screen segment length, closing near-duplicate
        trimmed on release).
      - "triangle"/"quadrilateral": click each vertex in turn; the shape
        auto-finishes after 3 or 4 clicks.
      - "arc": the center is always the fixed grid origin (the crosshair
        drawn by FreeDrawScene) - drag outward from anywhere to set radius
        and end angle in one gesture (start angle/thickness are numeric-
        only fields in the dialog - not practical to gesture precisely).
        Using a fixed origin instead of "wherever you first clicked" keeps
        the drag preview and the "Apply Parameters" preview centered at the
        exact same point, so the arc doesn't jump on release.
    `set_preview_points`/`set_preview_arc` let "Apply Parameters" show a
    shape built from typed numbers using the same preview path.
    """

    ORIGIN = QPointF(0, 0)
    MIN_SEGMENT_PX = 8.0
    VERTEX_COUNTS = {"triangle": 3, "quadrilateral": 4}

    def __init__(self):
        # QGraphicsView does not take ownership of its scene, so an
        # anonymous FreeDrawScene() passed straight into super().__init__()
        # has no surviving Python reference and gets garbage-collected
        # almost immediately, leaving self.scene() as None. Keep an
        # explicit attribute reference to keep it alive.
        self._owned_scene = FreeDrawScene()
        super().__init__(self._owned_scene)
        self.setRenderHint(QPainter.Antialiasing)
        # Same trailing-artifact fix as CanvasView: MinimalViewportUpdate
        # (the default) only repaints each changed item's own old+new
        # bounding box, which leaves faint grid remnants behind a moving/
        # resizing preview polygon (worst while dragging the arc preview).
        self.setViewportUpdateMode(QGraphicsView.FullViewportUpdate)
        self.mode = "freehand"
        self._drawing = False
        self.points: list[QPointF] = []
        self._preview_item = None
        self.on_shape_finished: Optional[Callable[[list], None]] = None
        self.on_arc_finished: Optional[Callable[[QPointF, QPointF], None]] = None

    def set_mode(self, mode: str):
        self.mode = mode
        self.reset()

    def reset(self):
        self._drawing = False
        self.points = []
        self._clear_preview()

    def set_preview_points(self, points: list[QPointF]):
        """Used by "Apply Parameters" to preview a shape built from typed
        numbers rather than a mouse gesture."""
        self.points = list(points)
        self._update_polygon_preview(self.points)

    def set_preview_arc(self, center: QPointF, radius_px: float, start_angle: float, end_angle: float, thickness_px: float):
        pts = arc_ring_points(radius_px, start_angle, end_angle, thickness_px)
        poly = QPolygonF([QPointF(center.x() + x, center.y() - y) for x, y in pts])
        self._set_preview_polygon(poly)

    def wheelEvent(self, event):
        factor = 1.15 if event.angleDelta().y() > 0 else 1 / 1.15
        self.scale(factor, factor)

    def mousePressEvent(self, event):
        if event.button() != Qt.LeftButton:
            super().mousePressEvent(event)
            return
        pos = self.mapToScene(event.pos())
        if self.mode == "freehand":
            self._drawing = True
            self.points = [pos]
            self._update_polygon_preview(self.points)
        elif self.mode in self.VERTEX_COUNTS:
            self.points.append(pos)
            self._update_polygon_preview(self.points)
            needed = self.VERTEX_COUNTS[self.mode]
            if len(self.points) >= needed:
                finished, self.points = self.points, []
                if self.on_shape_finished:
                    self.on_shape_finished(finished)
        elif self.mode == "arc":
            self._drawing = True
            self._preview_arc_drag(self.ORIGIN, pos)

    def mouseMoveEvent(self, event):
        pos = self.mapToScene(event.pos())
        if self.mode == "freehand" and self._drawing:
            last = self.points[-1]
            if (pos - last).manhattanLength() >= self.MIN_SEGMENT_PX:
                self.points.append(pos)
                self._update_polygon_preview(self.points)
        elif self.mode in self.VERTEX_COUNTS and self.points:
            self._update_polygon_preview(self.points + [pos])
        elif self.mode == "arc" and self._drawing:
            self._preview_arc_drag(self.ORIGIN, pos)
        else:
            super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        if event.button() != Qt.LeftButton:
            super().mouseReleaseEvent(event)
            return
        if self.mode == "freehand" and self._drawing:
            self._drawing = False
            points = self.points
            # A user closing the outline naturally brings the mouse back
            # near the starting point before releasing - drop that
            # near-duplicate trailing point so we don't store a degenerate
            # (near-zero-length) edge in the final polygon.
            if len(points) >= 2 and (points[-1] - points[0]).manhattanLength() < self.MIN_SEGMENT_PX * 1.5:
                points = points[:-1]
            self.points = points
            if len(points) >= 3 and self.on_shape_finished:
                self.on_shape_finished(points)
        elif self.mode == "arc" and self._drawing:
            self._drawing = False
            edge = self.mapToScene(event.pos())
            if (edge - self.ORIGIN).manhattanLength() >= self.MIN_SEGMENT_PX and self.on_arc_finished:
                self.on_arc_finished(self.ORIGIN, edge)
        # triangle/quadrilateral auto-finish inline in mousePressEvent.

    def _preview_arc_drag(self, center: QPointF, edge: QPointF):
        dx, dy = edge.x() - center.x(), edge.y() - center.y()
        radius_px = math.hypot(dx, dy)
        if radius_px < 1e-6:
            return
        end_angle = math.degrees(math.atan2(-dy, dx))
        if end_angle < 0:
            end_angle += 360.0
        self.set_preview_arc(center, radius_px, 0.0, end_angle, radius_px * 0.3)

    def _update_polygon_preview(self, points):
        if len(points) < 2:
            self._clear_preview()
            return
        self._set_preview_polygon(QPolygonF(points))

    def _set_preview_polygon(self, poly: QPolygonF):
        if self._preview_item is None:
            self._preview_item = self.scene().addPolygon(
                poly, QPen(QColor(59, 130, 246), 2), QBrush(QColor(59, 130, 246, 60))
            )
        else:
            self._preview_item.setPolygon(poly)

    def _clear_preview(self):
        if self._preview_item:
            self.scene().removeItem(self._preview_item)
            self._preview_item = None


