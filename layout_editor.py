    def _apply_quad_params(self):
        self._set_scene_points_from_meters([(x.value(), y.value()) for x, y in self.quad_spins])

    def _set_scene_points_from_meters(self, points_m):
        scene_points = [QPointF(x * SCALE, -y * SCALE) for x, y in points_m]
        self.draw_view.set_preview_points(scene_points)
        self._raw_points = scene_points
        self.save_btn.setEnabled(True)

    def _apply_arc_params(self):
        radius_px = self.arc_radius_spin.value() * SCALE
        thickness_px = self.arc_thickness_spin.value() * SCALE
        # Preview centered at the canvas origin - only radius/angles/
        # thickness are saved, the placed position comes from the drop.
        self.draw_view.set_preview_arc(
            QPointF(0, 0), radius_px, self.arc_start_spin.value(), self.arc_end_spin.value(), thickness_px
        )
        self.save_btn.setEnabled(True)

