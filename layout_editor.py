class AddItemCommand(QUndoCommand):
    """Adds a PlacedItem to the scene/items_list/config (redo) or removes it
    again (undo). `do_add`/`do_remove` are CanvasView's own `_add_item`/
    `_remove_item` (or ComponentManagerPanel's equivalents) - this command
    doesn't duplicate that bookkeeping, just calls it in either direction."""

    def __init__(self, do_add, do_remove, item: "PlacedItem", text="Add Component"):
        super().__init__(text)
        self._do_add = do_add
        self._do_remove = do_remove
        self.item = item

    def redo(self):
        self._do_add(self.item)

    def undo(self):
        self._do_remove(self.item)


class DeleteItemsCommand(QUndoCommand):
    """Inverse of AddItemCommand, for one or more items at once (e.g. a
    multi-select Delete)."""

    def __init__(self, do_add, do_remove, items, text="Delete Component(s)"):
        super().__init__(text)
        self._do_add = do_add
        self._do_remove = do_remove
        self.items = list(items)

    def redo(self):
        for item in self.items:
            self._do_remove(item)

    def undo(self):
        for item in self.items:
            self._do_add(item)


class MoveItemCommand(QUndoCommand):
    """One completed drag (mouse press to release) of a single PlacedItem -
    pushed once per drag, not per intermediate mouse-move, so undo steps
    line up with what the user actually did."""

    def __init__(self, item: "PlacedItem", old_pos: QPointF, new_pos: QPointF, text="Move Component"):
        super().__init__(text)
        self.item = item
        self.old_pos = QPointF(old_pos)
        self.new_pos = QPointF(new_pos)

    def _apply(self, pos: QPointF):
        self.item.setPos(pos)
        self.item.model.x, self.item.model.y = from_scene_pos(pos)
        # Undo/redo of a move bypasses mouseReleaseEvent's own invalidation
        # (see there) - do it here too, since this changes the item's
        # keypoints just as much as the original drag did.
        if self.item.scene():
            for view in self.item.scene().views():
                if hasattr(view, "invalidate_points_edges_cache"):
                    view.invalidate_points_edges_cache()

    def redo(self):
        self._apply(self.new_pos)

    def undo(self):
        self._apply(self.old_pos)


class PropertyEditCommand(QUndoCommand):
    """One property-panel field edit. `apply_fn(item, value)` performs both
    the model mutation and whatever visual refresh that field needs (each
    field type's refresh differs - resize, re-rotate, brush re-sync, etc. -
    so the panel supplies it rather than this generic command knowing about
    every item type)."""

    def __init__(self, item, apply_fn, old_value, new_value, text="Edit Property"):
        super().__init__(text)
        self.item = item
        self.apply_fn = apply_fn
        self.old_value = old_value
        self.new_value = new_value

    def redo(self):
        self.apply_fn(self.item, self.new_value)

    def undo(self):
        self.apply_fn(self.item, self.old_value)


class CanvasView(QGraphicsView):
    def __init__(self, scene: SnapGuideScene, items, on_items_changed=None, config=None):
        super().__init__(scene)
        self.items_list = items
        self.config = config
        self.on_items_changed = on_items_changed
        self.get_template: Optional[Callable[[str], Optional[ComponentTemplate]]] = None
        self.on_mouse_moved: Optional[Callable[[float, float], None]] = None
        self._clipboard_models = []  # one or more deepcopy'd models - a group copy/paste
        self._last_mouse_scene_pos: Optional[QPointF] = None
        # Cache for _all_points_and_edges() - every item's keypoints/edges
        # only actually change when an item is added/removed or a property
        # edit resizes/moves one (see invalidate_points_edges_cache(), called
        # from those choke points), not on every single mouse-move pixel
        # that just reads this list for the hover coordinate snap.
        self._points_edges_cache: Optional[tuple] = None
        # Set externally by MainWindow once both exist. None (the
        # standalone-demo/no-undo case) falls back to applying mutations
        # directly instead of going through a command.
        self.undo_stack: Optional[QUndoStack] = None
        # An interactive drawing tool (path_tool.PathDrawTool) that gets
        # mouse/key events before the default select/drag handling.
        self.tool = None
        # Called first by Delete; returns True if it deleted something itself.
        self.on_delete_extra = None
        self._pan_tool_active = False
        self._middle_pan_active = False
        self._middle_pan_last_pos = None
        # Measure tool: click a point (a keypoint/grid snap, like the live
        # coordinate readout) then a second point to measure length+angle;
        # click an existing component edge then a second edge to measure
        # the angle BETWEEN them instead - AutoCAD-style point-to-point
        # distance vs. line-to-line angle. `_measure_pending` is None, or
        # ("point"|"free", QPointF), or ("edge", (p1, p2)).
        self._measure_mode = False
        self._measure_pending: Optional[tuple] = None
        self.setAcceptDrops(True)
        self.setDragMode(QGraphicsView.RubberBandDrag)
        # Mouse-move events normally only arrive while a button is held -
        # tracking needs to be on (on the actual viewport widget, since
        # QGraphicsView delivers mouse events through it, not itself) to
        # get a live coordinate readout while just hovering, not dragging.
        self.setMouseTracking(True)
        self.viewport().setMouseTracking(True)
        self.setRenderHint(QPainter.Antialiasing)
        self.setTransformationAnchor(QGraphicsView.AnchorUnderMouse)
        # Needed to actually receive key events (Ctrl+C/V, Delete) - a plain
        # QGraphicsView defaults to NoFocus.
        self.setFocusPolicy(Qt.StrongFocus)
        # MinimalViewportUpdate (the default) only repaints each moved/rotated
        # item's own old+new bounding box; the custom grid background redraw
        # for that patch can leave faint trailing artifacts, especially with
        # rotated (diamond-shaped) bounding regions. Full repaint avoids it -
        # a non-issue at this scene scale.
        self.setViewportUpdateMode(QGraphicsView.FullViewportUpdate)

    def dragEnterEvent(self, event):
        if event.mimeData().hasFormat("application/x-component-template"):
            event.acceptProposedAction()
        else:
            super().dragEnterEvent(event)

    def dragMoveEvent(self, event):
        if event.mimeData().hasFormat("application/x-component-template"):
            event.acceptProposedAction()
        else:
            super().dragMoveEvent(event)

    def dropEvent(self, event):
        mime = event.mimeData()
        if mime.hasFormat("application/x-component-template"):
            name = bytes(mime.data("application/x-component-template")).decode("utf-8")
            template = self.get_template(name) if self.get_template else None
            if template:
                scene_pos = self.mapToScene(event.position().toPoint())
                world_x, world_y = from_scene_pos(scene_pos)
                existing_ids = (i.model.id for i in self.items_list if i.kind == template.kind)
                new_id = next_indexed_id(existing_ids, template.kind)
                model = template.factory(new_id)
                model.x, model.y = world_x, world_y
                item_cls = ITEM_CLASS_FOR_KIND[template.kind]
                self._add_item(item_cls(model), text=f"Add {template.kind}")
            event.acceptProposedAction()
        else:
            super().dropEvent(event)

    def _do_add_item(self, item: PlacedItem) -> PlacedItem:
        """The actual add mutation - scene, items_list, config. Called
        directly (no undo stack) or as an AddItemCommand's redo/DeleteItems
        Command's undo."""
        self.scene().addItem(item)
        self.items_list.append(item)
        if self.config is not None:
            getattr(self.config, CONFIG_LIST_ATTR_FOR_KIND[item.kind]).append(item.model)
        self.invalidate_points_edges_cache()
        if self.on_items_changed:
            self.on_items_changed()
        return item

    def _do_remove_item(self, item: PlacedItem):
        """The actual remove mutation - inverse of `_do_add_item`."""
        self.scene().removeItem(item)
        self.items_list.remove(item)
        if self.config is not None:
            getattr(self.config, CONFIG_LIST_ATTR_FOR_KIND[item.kind]).remove(item.model)
        self.invalidate_points_edges_cache()
        if self.on_items_changed:
            self.on_items_changed()

    def _add_item(self, item: PlacedItem, text: str = "Add Component") -> PlacedItem:
        """Public add entry point: goes through the undo stack when one is
        attached, otherwise applies directly."""
        if self.undo_stack is not None:
            self.undo_stack.push(AddItemCommand(self._do_add_item, self._do_remove_item, item, text))
        else:
            self._do_add_item(item)
        return item

    def _remove_item(self, item: PlacedItem, text: str = "Delete Component"):
        """Public remove entry point - see `_add_item`."""
        if self.undo_stack is not None:
            self.undo_stack.push(DeleteItemsCommand(self._do_add_item, self._do_remove_item, [item], text))
        else:
            self._do_remove_item(item)

    def wheelEvent(self, event):
        factor = 1.15 if event.angleDelta().y() > 0 else 1 / 1.15
        self.scale(factor, factor)

    def set_pan_mode(self, enabled: bool):
        """Toggle a persistent "Pan Tool" (left-click-drag always pans the
        view instead of selecting/rubber-banding) - the toggle-button
        equivalent of holding Space, for trackpad/one-button-mouse users
        who'd rather not hold a key down."""
        self._pan_tool_active = enabled
        self.setDragMode(QGraphicsView.ScrollHandDrag if enabled else QGraphicsView.RubberBandDrag)

    def set_measure_mode(self, enabled: bool):
        """Toggle the Measure Tool: while active, left-clicks select points
        (snapped to keypoints/grid) or existing component edges (at any
        angle) instead of selecting or dragging components."""
        self._measure_mode = enabled
        self._measure_pending = None
        if self.scene():
            self.scene().clear_measure_preview()
        self.setCursor(Qt.CrossCursor if enabled else Qt.ArrowCursor)

    def _measure_target_at(self, view_pos):
        raw_scene_pos = self.mapToScene(view_pos)
        points, edges = self._all_points_and_edges()
        return _find_measure_target(raw_scene_pos, points, edges, self._snap_tolerance_scene_units())

    def _draw_measure_selection(self, target):
        """Mark a just-clicked (now confirmed, not just hovered) target:
        a point marker, or - for an edge - nothing yet, since a single
        selected edge isn't meaningful on its own until a second one
        completes an angle measurement (drawn together in add_measure_angle)."""
        kind, value = target
        if kind != "edge":
            self.scene().add_measure_point(value)

    def _handle_measure_click(self, view_pos):
        target = self._measure_target_at(view_pos)
        kind, value = target

        if self._measure_pending is None:
            self._measure_pending = target
            self._draw_measure_selection(target)
            return

        prev_kind, prev_value = self._measure_pending
        prev_is_point = prev_kind in ("point", "free")
        this_is_point = kind in ("point", "free")

        if prev_is_point and this_is_point:
            # Point + point -> length (and angle-from-X-axis) between them.
            self._draw_measure_selection(target)
            self.scene().add_measure_line(prev_value, value)
            self._measure_pending = None
        elif prev_kind == "edge" and kind == "edge":
            # Edge + edge -> the angle BETWEEN the two lines.
            self.scene().add_measure_angle(prev_value, value)
            self._measure_pending = None
        else:
            # Mismatched types (e.g. a point was pending, but this click hit
            # an edge instead) - don't try to measure across types, just
            # restart fresh with whatever was actually just clicked.
            self._measure_pending = target
            self._draw_measure_selection(target)

    def keyPressEvent(self, event):
        if self.tool is not None and self.tool.key_press(event):
            event.accept()
            return
        # Don't fight the Pan Tool toggle: if it's already active, Space
        # has nothing to add (already in ScrollHandDrag), and releasing
        # Space later must not drop back to RubberBandDrag out from under it.
        if event.key() == Qt.Key_Space and not self._pan_tool_active:
            self.setDragMode(QGraphicsView.ScrollHandDrag)
        elif event.matches(QKeySequence.Copy):
            self._copy_selected()
        elif event.matches(QKeySequence.Paste):
            self._paste_clipboard()
        elif event.key() in (Qt.Key_Delete, Qt.Key_Backspace):
            self._delete_selected()
        super().keyPressEvent(event)

    def keyReleaseEvent(self, event):
        if event.key() == Qt.Key_Space and not self._pan_tool_active:
            self.setDragMode(QGraphicsView.RubberBandDrag)
        super().keyReleaseEvent(event)

    def mousePressEvent(self, event):
        # Middle-mouse-drag pans regardless of the current tool/drag mode -
        # the same universal gesture CAD tools (AutoCAD, Fusion360) and
        # browsers use, so panning never requires switching tools or
        # holding Space at all.
        if event.button() == Qt.MiddleButton:
            self._middle_pan_active = True
            self._middle_pan_last_pos = event.pos()
            self.setCursor(Qt.ClosedHandCursor)
            event.accept()
            return
        if self.tool is not None and self.tool.mouse_press(event):
            event.accept()
            return
        if self._measure_mode and event.button() == Qt.LeftButton:
            self._handle_measure_click(event.pos())
            event.accept()
            return
        if self._measure_mode and event.button() == Qt.RightButton:
            # Cancel an in-progress selection - a point marker (if any)
            # stays on the canvas, it's just no longer waiting for a second
            # click to complete a measurement.
            self._measure_pending = None
            event.accept()
            return
        super().mousePressEvent(event)

    def _snap_tolerance_scene_units(self) -> float:
        scale = self.transform().m11()
        return SNAP_TOLERANCE_PX / scale if scale > 1e-6 else SNAP_TOLERANCE_PX

    def _all_points_and_edges(self):
        """Every placed item's keypoints/edges, in scene coords - the
        candidate set both the live coordinate readout and the measure
        tool snap free (non-dragged) points against.

        Cached across calls (see invalidate_points_edges_cache()) since this
        used to be recomputed - a full scan + mapToScene of every placed
        item - on every single mouse-move pixel while just hovering, not
        only while dragging."""
        if self._points_edges_cache is not None:
            return self._points_edges_cache
        points, edges = [], []
        for item in self.items_list:
            points.extend(item.mapToScene(p) for p in item._local_key_points())
            edges.extend((item.mapToScene(p1), item.mapToScene(p2)) for p1, p2 in item._local_edges())
        self._points_edges_cache = (points, edges)
        return self._points_edges_cache

    def invalidate_points_edges_cache(self):
        """Call whenever an item is added/removed or a property edit
        changes an item's geometry (resize, rotate, reposition via the
        properties panel) - anything that would make the cached list in
        _all_points_and_edges() stale. Deliberately NOT called on every
        drag-move; the item being dragged snapping against its own
        pre-drag position is an acceptable, self-correcting staleness that
        clears itself on the drag's next add/remove/property-edit."""
        self._points_edges_cache = None

    def mouseMoveEvent(self, event):
        self._last_mouse_scene_pos = self.mapToScene(event.pos())
        if self._measure_mode and self.scene():
            # Live "what would clicking here select" feedback - satisfies
            # the tool actually feeling "attached" to keypoints/grid/edges
            # rather than only revealing what it snapped to after the fact.
            self.scene().show_measure_preview(self._measure_target_at(event.pos()))
        if self.on_mouse_moved:
            points, edges = self._all_points_and_edges()
            snapped = _snap_free_point(self._last_mouse_scene_pos, points, edges, self._snap_tolerance_scene_units())
            world_x, world_y = from_scene_pos(snapped)
            self.on_mouse_moved(world_x, world_y)
        if self._middle_pan_active:
            pos = event.pos()
            delta = pos - self._middle_pan_last_pos
            self._middle_pan_last_pos = pos
            h_bar = self.horizontalScrollBar()
            v_bar = self.verticalScrollBar()
            h_bar.setValue(h_bar.value() - delta.x())
            v_bar.setValue(v_bar.value() - delta.y())
            event.accept()
            return
        if self.tool is not None and self.tool.mouse_move(event):
            event.accept()
            return
        super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        if event.button() == Qt.MiddleButton and self._middle_pan_active:
            self._middle_pan_active = False
            self.unsetCursor()
            event.accept()
            return
        if self.tool is not None and self.tool.mouse_release(event):
            event.accept()
            return
        super().mouseReleaseEvent(event)

    def mouseDoubleClickEvent(self, event):
        if self.tool is not None and self.tool.mouse_double_click(event):
            event.accept()
            return
        super().mouseDoubleClickEvent(event)

    def _copy_selected(self):
        selected = [i for i in self.scene().selectedItems() if isinstance(i, PlacedItem)]
        if selected:
            self._clipboard_models = [deepcopy(i.model) for i in selected]

    def _paste_clipboard(self):
        if not self._clipboard_models:
            return
        # Paste the whole group at the mouse position instead of the
        # original spot: shift every copied model by the same offset, from
        # the group's centroid to wherever the cursor currently is over the
        # canvas, so the copied items keep their layout relative to each
        # other but land where the user is pointing, not stacked on top of
        # the originals. Falls back to the old "nudge by half a unit" if
        # the mouse has never been over the canvas yet (e.g. paste
        # triggered before any mouse movement was recorded).
        cx = sum(model.x for model in self._clipboard_models) / len(self._clipboard_models)
        cy = sum(model.y for model in self._clipboard_models) / len(self._clipboard_models)
        if self._last_mouse_scene_pos is not None:
            target_x, target_y = from_scene_pos(self._last_mouse_scene_pos)
        else:
            target_x, target_y = cx + 0.5, cy + 0.5
        offset_x, offset_y = target_x - cx, target_y - cy

        multi = len(self._clipboard_models) > 1
        text = f"Paste {len(self._clipboard_models)} Components" if multi else "Paste Component"
        if self.undo_stack is not None and multi:
            self.undo_stack.beginMacro(text)
        new_items = []
        for model in self._clipboard_models:
            new_model = deepcopy(model)
            kind = KIND_FOR_MODEL_CLASS[type(new_model)]
            existing_ids = {i.model.id for i in self.items_list if i.kind == kind}
            new_model.id = unique_incremented_id(existing_ids, new_model.id)
            new_model.x += offset_x
            new_model.y += offset_y
            item_cls = ITEM_CLASS_FOR_KIND[kind]
            new_items.append(self._add_item(item_cls(new_model), text=text))
        if self.undo_stack is not None and multi:
            self.undo_stack.endMacro()

        self.scene().clearSelection()
        for item in new_items:
            item.setSelected(True)

    def _delete_selected(self):
        if self.on_delete_extra is not None and self.on_delete_extra():
            return  # e.g. selected sketch entities (layout_editor_cad.py)
        selected = [i for i in self.scene().selectedItems() if isinstance(i, PlacedItem)]
        if not selected:
            return
        # One combined command for the whole selection, not one per item -
        # a multi-select delete should undo as a single step.
        if self.undo_stack is not None:
            text = "Delete Component" if len(selected) == 1 else f"Delete {len(selected)} Components"
            self.undo_stack.push(DeleteItemsCommand(self._do_add_item, self._do_remove_item, selected, text))
        else:
            for item in selected:
                self._do_remove_item(item)


def _field_specs_for(item: PlacedItem):
    """(kind, attr, label, *args) descriptors for the properties panel,
    chosen dynamically by the selected item's type/shape - mirrors
    editor_ui.py's `show_props_for` showing different fields per component
    type, but rebuilding a Qt form instead of manually hiding pygame_gui
    widgets."""
    specs = [
        ("float", "x", "X", -1000.0, 1000.0, 0.1),
        ("float", "y", "Y", -1000.0, 1000.0, 0.1),
    ]
    if hasattr(item.model, "rotation"):
        # Sink has no `rotation` field at all (always drawn upright,
        # matching the pygame app), so skip the row entirely for it
        # instead of showing a control that can't do anything.
        specs.append(("float", "rotation", "Rotation", -360.0, 360.0, 1.0))
    if isinstance(item, BeltItem):
        specs.append(("float", "directionAngle", "Direction", -360.0, 360.0, 1.0))
        if item.is_path():
            specs.append(("float", "beltWidth", "Width", 0.05, 100.0, 0.05))
        elif item.is_curved():
            specs.append(("float", "radius", "Radius", 0.1, 100.0, 0.1))
            specs.append(("float", "startAngle", "StartAng", -360.0, 360.0, 1.0))
            specs.append(("float", "endAngle", "EndAng", -360.0, 360.0, 1.0))
            specs.append(("float", "beltWidth", "Width", 0.05, 100.0, 0.05))
        elif not item.is_custom_shape():
            specs.append(("float", "length", "Length", 0.1, 100.0, 0.1))
            specs.append(("float", "beltWidth", "Width", 0.1, 100.0, 0.1))
        specs.append(("float", "speed", "Speed", -50.0, 50.0, 0.1))
        specs.append(("float", "transition_momentum_duration", "Trans Dur", 0.0, 10.0, 0.1))
    elif isinstance(item, SensorItem):
        specs.append(("float", "width", "Width", 0.05, 50.0, 0.05))
        specs.append(("float", "height", "Height", 0.05, 50.0, 0.05))
        specs.append(("text", "label", "Label"))
        specs.append(("combo", "sensorType", "Type", ["ir", "laser_banner"]))
        if item.model.sensorType == "laser_banner":
            specs.append(("int", "laserCount", "Beams", 1, 128))
            specs.append(("float", "beamDistance", "BeamDist", 0.01, 5.0, 0.01))
    elif isinstance(item, SourceItem):
        specs.append(("float", "interval", "Interval", 0.1, 3600.0, 0.1))
        specs.append(("float", "minWidth", "MinW", 0.05, 50.0, 0.05))
        specs.append(("float", "maxWidth", "MaxW", 0.05, 50.0, 0.05))
        specs.append(("float", "minHeight", "MinH", 0.05, 50.0, 0.05))
        specs.append(("float", "maxHeight", "MaxH", 0.05, 50.0, 0.05))
        specs.append(("text", "label", "Label"))
    elif isinstance(item, SinkItem):
        specs.append(("float", "width", "Width", 0.05, 50.0, 0.05))
        specs.append(("float", "height", "Height", 0.05, 50.0, 0.05))
        specs.append(("text", "label", "Label"))
    elif isinstance(item, ButtonItem):
        specs.append(("float", "width", "Width", 0.05, 50.0, 0.05))
        specs.append(("float", "height", "Height", 0.05, 50.0, 0.05))
        specs.append(("text", "label", "Label"))
        # `sensor_states` (pressed/released) is live and momentary - driven
        # only by mouse press/release while playing (see ButtonItem), not
        # something to hand-edit here.
    elif isinstance(item, LedItem):
        specs.append(("float", "radius", "Radius", 0.02, 50.0, 0.02))
        specs.append(("text", "label", "Label"))
        specs.append(("bool", "isOn", "On"))
    return specs


class PropertiesPanel(QWidget):
    """Docked property editor - replaces editor_ui.py's hand-positioned
    widgets. Rebuilds its field rows on selection change to match the
    selected item's type (see `_field_specs_for`)."""

    def __init__(self, scene: SnapGuideScene, items, on_model_changed=None):
        super().__init__()
        self.scene = scene
        self.items_list = items
        self.on_model_changed = on_model_changed
        # Set externally by MainWindow once both exist.
        self.undo_stack: Optional[QUndoStack] = None
        self.current: Optional[PlacedItem] = None
        self.spins = {}
        self.texts = {}
        self.combos = {}
        self.checkboxes = {}

        outer = QVBoxLayout(self)
        # `self.form` holds only Id + the dynamic per-type fields, since
        # QFormLayout.removeRow() (used by _clear_dynamic_rows below) does
        # not just detach a row's widgets - it deletes them. Color needs to
        # survive every rebuild, so it lives in its own layout that
        # _clear_dynamic_rows never touches.
        self.form = QFormLayout()
        outer.addLayout(self.form)
        self.id_edit = QLineEdit()
        self.id_edit.editingFinished.connect(self._apply_id)
        self.form.addRow("Id:", self.id_edit)

        color_form = QFormLayout()
        self.color_btn = QPushButton("-")
        self.color_btn.clicked.connect(self._pick_color)
        color_form.addRow("Color:", self.color_btn)
        outer.addLayout(color_form)
        outer.addStretch(1)

        self.setEnabled(False)
        scene.selectionChanged.connect(self._on_selection_changed)

    def _on_selection_changed(self):
        selected = [i for i in self.scene.selectedItems() if isinstance(i, PlacedItem)]
        if len(selected) == 1:
            self.current = selected[0]
            self._rebuild_fields()
            self._load()
            self.setEnabled(True)
        else:
            self.current = None
            self._clear_dynamic_rows()
            self._update_color_swatch()
            self.setEnabled(False)

    def _clear_dynamic_rows(self):
        while self.form.rowCount() > 1:
            self.form.removeRow(1)
        self.spins.clear()
        self.texts.clear()
        self.combos.clear()
        self.checkboxes.clear()

    def _rebuild_fields(self):
        self._clear_dynamic_rows()
        item = self.current
        if not item:
            return
        for spec in _field_specs_for(item):
            field_kind, attr, label = spec[0], spec[1], spec[2]
            if field_kind == "float":
                _, _, _, lo, hi, step = spec
                widget = QDoubleSpinBox()
                widget.setRange(lo, hi)
                widget.setDecimals(3)
                widget.setSingleStep(step)
                widget.valueChanged.connect(lambda v, a=attr: self._apply_field(a, v))
                self.spins[attr] = widget
            elif field_kind == "int":
                _, _, _, lo, hi = spec
                widget = QSpinBox()
                widget.setRange(lo, hi)
                widget.valueChanged.connect(lambda v, a=attr: self._apply_field(a, v))
                self.spins[attr] = widget
            elif field_kind == "text":
                widget = QLineEdit()
                widget.editingFinished.connect(lambda a=attr: self._apply_text_field(a))
                self.texts[attr] = widget
            elif field_kind == "combo":
                _, _, _, options = spec
                widget = QComboBox()
                widget.addItems(options)
                widget.currentTextChanged.connect(lambda text, a=attr: self._apply_combo_field(a, text))
                self.combos[attr] = widget
            elif field_kind == "bool":
                widget = QCheckBox()
                widget.toggled.connect(lambda checked, a=attr: self._apply_bool_field(a, checked))
                self.checkboxes[attr] = widget
            else:
                continue
            self.form.addRow(f"{label}:", widget)

    # Some model fields are `Optional[...] = None` (e.g. Sensor.laserCount/
    # beamDistance when a config never set them) - QSpinBox/QDoubleSpinBox
    # both raise TypeError on setValue(None), so fall back to a sensible
    # per-field default at *display* time rather than crashing (mirrors
    # physics.py's own `laser_count_val if ... is not None else 16` pattern
    # - it doesn't silently mutate the model, just treats None as this
    # value for display until the user actually edits it).
    _OPTIONAL_FIELD_DEFAULTS = {"laserCount": 16, "beamDistance": 0.05}

    def _load(self):
        item = self.current
        if not item:
            return
        for widget in (*self.spins.values(), *self.texts.values(), *self.combos.values(), *self.checkboxes.values()):
            widget.blockSignals(True)

        self.id_edit.blockSignals(True)
        self.id_edit.setText(item.model.id)
        self.id_edit.setStyleSheet("")
        self.id_edit.setToolTip("")
        self.id_edit.blockSignals(False)

        for attr, widget in self.spins.items():
            value = getattr(item.model, attr)
            if value is None:
                value = self._OPTIONAL_FIELD_DEFAULTS.get(attr, 0)
            widget.setValue(value)
        for attr, widget in self.texts.items():
            widget.setText(str(getattr(item.model, attr) or ""))
        for attr, widget in self.combos.items():
            widget.setCurrentText(str(getattr(item.model, attr)))
        for attr, widget in self.checkboxes.items():
            widget.setChecked(bool(getattr(item.model, attr)))

        for widget in (*self.spins.values(), *self.texts.values(), *self.combos.values(), *self.checkboxes.values()):
            widget.blockSignals(False)
        self._update_color_swatch()

    def _push_property_change(self, item, attr: str, old_value, new_value, do_apply, text=None):
        """Route a property edit through the undo stack (if attached),
        otherwise apply it directly. `do_apply(item, attr, value)` performs
        the actual model mutation + visual refresh for this specific field -
        shared between the live edit and undo/redo replay."""
        apply_fn = lambda it, v, a=attr: do_apply(it, a, v)
        if self.undo_stack is not None:
            self.undo_stack.push(PropertyEditCommand(item, apply_fn, old_value, new_value, text or f"Edit {attr}"))
        else:
            apply_fn(item, new_value)

    def _resync_widget(self, item, attr: str):
        """After undo/redo replays a value (or any programmatic apply),
        refresh the ON-SCREEN widget for that field too, if the affected
        item is still selected - otherwise the panel would show a stale
        value until the next selection change."""
        if item is not self.current:
            return
        value = getattr(item.model, attr, None)
        for widgets, setter in (
            (self.spins, lambda w, v: w.setValue(v if v is not None else self._OPTIONAL_FIELD_DEFAULTS.get(attr, 0))),
            (self.texts, lambda w, v: w.setText(str(v or ""))),
            (self.combos, lambda w, v: w.setCurrentText(str(v))),
            (self.checkboxes, lambda w, v: w.setChecked(bool(v))),
        ):
            widget = widgets.get(attr)
            if widget is not None:
                widget.blockSignals(True)
                setter(widget, value)
                widget.blockSignals(False)
                return

    def _apply_field(self, attr: str, value):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        if old_value == value:
            return
        self._push_property_change(item, attr, old_value, value, self._do_apply_field)

    def _do_apply_field(self, item, attr: str, value):
        """Apply a single edited field, touching only the Qt geometry that
        field actually affects - not all of setPos/setRotation/set_size on
        every keystroke, which used to re-trigger the drag-snap logic (and
        its guide-line overlay) even for unrelated edits like `speed`."""
        setattr(item.model, attr, value)
        if attr in ("x", "y"):
            item.setPos(to_scene_pos(item.model.x, item.model.y))
        elif attr == "rotation":
            item.setRotation(-value)
        elif isinstance(item, BeltItem) and item.is_curved() and attr in ("radius", "startAngle", "endAngle", "beltWidth"):
            item.set_arc_params(item.model.radius, item.model.startAngle, item.model.endAngle, item.model.beltWidth)
        elif isinstance(item, BeltItem) and item.is_path() and attr == "beltWidth":
            item.sync_from_model()
        elif isinstance(item, BeltItem) and not item.is_curved() and attr in ("length", "beltWidth"):
            item.set_size(item.model.length, item.model.beltWidth)
        elif attr in ("width", "height") and isinstance(item, (SensorItem, SinkItem, ButtonItem)):
            item.set_size(item.model.width, item.model.height)
        elif attr in ("maxWidth", "maxHeight") and isinstance(item, SourceItem):
            item.set_size(item.model.maxWidth, item.model.maxHeight)
        elif attr == "radius" and isinstance(item, LedItem):
            item.set_size(item.model.radius)
        item.update()
        # This is the only field-edit path that can move/resize an item's
        # keypoints (position, rotation, length, size, arc params) - the
        # view's cached keypoint/edge list (CanvasView._all_points_and_edges)
        # would otherwise keep offering this item's PRE-edit geometry as a
        # hover/measure snap target for the rest of the session.
        if self.scene:
            for view in self.scene.views():
                if hasattr(view, "invalidate_points_edges_cache"):
                    view.invalidate_points_edges_cache()
        self._resync_widget(item, attr)

    def _apply_text_field(self, attr: str):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        new_value = self.texts[attr].text()
        if old_value == new_value:
            return
        self._push_property_change(item, attr, old_value, new_value, self._do_apply_text_field)

    def _do_apply_text_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        item.update()
        self._resync_widget(item, attr)

    def _apply_bool_field(self, attr: str, checked: bool):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        if bool(old_value) == checked:
            return
        self._push_property_change(item, attr, old_value, checked, self._do_apply_bool_field)

    def _do_apply_bool_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        item.update()
        self._resync_widget(item, attr)

    def _apply_combo_field(self, attr: str, text: str):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        if old_value == text:
            return
        self._push_property_change(item, attr, old_value, text, self._do_apply_combo_field)

    def _do_apply_combo_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        if attr == "sensorType" and value == "laser_banner":
            item.model.laserCount = item.model.laserCount or 16
            item.model.beamDistance = item.model.beamDistance or 0.05
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        item.update()
        if item is self.current:
            if attr == "sensorType":
                # Adding/removing laserCount/beamDistance rows here (mid-
                # signal, inside this very combo box's own currentTextChanged
                # handler) would delete a widget while it's still emitting -
                # defer one tick so Qt finishes the current event first.
                QTimer.singleShot(0, self._rebuild_and_reload)
            else:
                self._resync_widget(item, attr)

    def _rebuild_and_reload(self):
        if not self.current:
            return
        self._rebuild_fields()
        self._load()

    def _apply_id(self):
        item = self.current
        if not item:
            return
        new_id = self.id_edit.text().strip()
        other_ids = {i.model.id for i in self.items_list if i is not item}
        if not new_id or new_id in other_ids:
            self.id_edit.setStyleSheet("border: 1px solid #ff5555;")
            self.id_edit.setToolTip("Id must be non-empty and unique - reverted")
            self.id_edit.setText(item.model.id)
            return
        self.id_edit.setStyleSheet("")
        self.id_edit.setToolTip("")
        old_id = item.model.id
        if old_id == new_id:
            return
        self._push_property_change(item, "id", old_id, new_id, self._do_apply_id, text="Edit Id")

    def _do_apply_id(self, item, attr: str, value):
        item.model.id = value
        item.update()
        if self.on_model_changed:
            self.on_model_changed()
        if item is self.current:
            self.id_edit.blockSignals(True)
            self.id_edit.setText(value)
            self.id_edit.blockSignals(False)

    def _pick_color(self):
        # Source/Sink have no `.color` field at all - visualizer.py draws
        # them with fixed colors too, so there's nothing to persist a pick
        # to. _update_color_swatch disables the button for these kinds.
        if not self.current or not hasattr(self.current.model, "color"):
            return
        item = self.current
        chosen = QColorDialog.getColor(QColor(item.model.color), self, "Color")
        if not chosen.isValid():
            return
        old_color, new_color = item.model.color, chosen.name()
        if old_color == new_color:
            return
        self._push_property_change(item, "color", old_color, new_color, self._do_apply_color, text="Edit Color")

    def _do_apply_color(self, item, attr: str, value):
        item.model.color = value
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        if item is self.current:
            self._update_color_swatch()

    def _update_color_swatch(self):
        if self.current and hasattr(self.current.model, "color"):
            self.color_btn.setEnabled(True)
            self.color_btn.setStyleSheet(f"background-color: {self.current.model.color};")
            self.color_btn.setText(self.current.model.color)
        elif self.current:
            self.color_btn.setEnabled(False)
            self.color_btn.setStyleSheet("")
            self.color_btn.setText("N/A")
        else:
            self.color_btn.setEnabled(False)
            self.color_btn.setStyleSheet("")
            self.color_btn.setText("-")


class ComponentManagerPanel(QWidget):
    """Lists every component in the scene - the "manage all placed
    components" list ask (distinct from the drag-source palette):
    select/duplicate/delete any placed belt or sensor, mirroring
    editor_ui.py's pygame "Component Manager" window but as a normal Qt
    dock instead of a hand-positioned pygame_gui window.
    """

    def __init__(self, scene: SnapGuideScene, items, view: QGraphicsView, config=None):
        super().__init__()
        self.scene = scene
        self.items_list = items
        self.view = view
        self.config = config

        layout = QVBoxLayout(self)
        self.list_widget = QListWidget()
        layout.addWidget(self.list_widget)

        btn_row = QHBoxLayout()
        self.select_btn = QPushButton("Select")
        self.duplicate_btn = QPushButton("Duplicate")
        self.delete_btn = QPushButton("Delete")
        for btn in (self.select_btn, self.duplicate_btn, self.delete_btn):
            btn_row.addWidget(btn)
        layout.addLayout(btn_row)

        self.list_widget.itemSelectionChanged.connect(self._select)
        self.select_btn.clicked.connect(self._select)
        self.duplicate_btn.clicked.connect(self._duplicate)
        self.delete_btn.clicked.connect(self._delete)

        self.refresh()

    def refresh(self):
        self.list_widget.blockSignals(True)
        self.list_widget.clear()
        for item in self.items_list:
            row = QListWidgetItem(f"{item.kind:<7}{item.model.id}")
            row.setData(Qt.UserRole, item)
            self.list_widget.addItem(row)
        self.list_widget.blockSignals(False)

    def _current_item(self) -> Optional[PlacedItem]:
        row = self.list_widget.currentItem()
        return row.data(Qt.UserRole) if row else None

    def _select(self):
        item = self._current_item()
        if not item:
            return
        self.scene.clearSelection()
        item.setSelected(True)
        self.view.centerOn(item)

    def _duplicate(self):
        item = self._current_item()
        if not item:
            return
        new_model = deepcopy(item.model)
        existing_ids = {i.model.id for i in self.items_list if i.kind == item.kind}
        new_model.id = unique_incremented_id(existing_ids, item.model.id)
        new_model.x += 0.5
        new_model.y += 0.5
        item_cls = type(item)
        # Routed through CanvasView's own add (undo-aware, and the single
        # place that already knows how to update scene/items_list/config
        # together) rather than duplicating that bookkeeping here.
        self.view._add_item(item_cls(new_model), text="Duplicate Component")
        self.refresh()

    def _delete(self):
        item = self._current_item()
        if not item:
            return
        self.view._remove_item(item, text="Delete Component")
        self.refresh()


