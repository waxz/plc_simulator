def build_items_from_config(config, scene: QGraphicsScene, items_list: list):
    """Populate `items_list`/`scene` from a real loaded `SimulatorConfig`,
    wrapping the exact same model instances `config` holds (not copies) -
    so that a `PhysicsEngine` running against the same `config` mutates the
    very objects these items already reference, with no extra syncing
    needed for e.g. sensor state.
    """
    for model in config.belts:
        item = BeltItem(model)
        scene.addItem(item)
        items_list.append(item)
    for model in config.sensors:
        item = SensorItem(model)
        scene.addItem(item)
        items_list.append(item)
    for model in config.sources:
        item = SourceItem(model)
        scene.addItem(item)
        items_list.append(item)
    for model in config.sinks:
        item = SinkItem(model)
        scene.addItem(item)
        items_list.append(item)
    for model in config.buttons:
        if model.panel:
            continue                # a control panel's element: drawn by its panel
        item = ButtonItem(model)
        scene.addItem(item)
        items_list.append(item)
    for model in config.leds:
        if model.panel:
            continue
        item = LedItem(model)
        scene.addItem(item)
        items_list.append(item)
    for kind in ("elevator", "turntable", "transfer", "pallet", "stopper", "robot", "scanner", "diverter", "accumulator",
                 "door", "safety", "panel"):
        for model in getattr(config, CONFIG_LIST_ATTR_FOR_KIND[kind]):
            item = ITEM_CLASS_FOR_KIND[kind](model)
            scene.addItem(item)
            items_list.append(item)


