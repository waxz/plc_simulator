class AddItemCommand(QUndoCommand):
    """Adds a PlacedItem to the scene/items_list/config (redo) or removes it
    again (undo). `do_add`/`do_remove` are CanvasView's own `_add_item`/
    `_remove_item` (or ComponentManagerPanel's equivalents) - this command
    doesn't duplicate that bookkeeping, just calls it in either direction."""

    def __init__(self, do_add, do_remove, item: "PlacedItem", text="Add Component"):
        super().__init__(text)
        self._do_add = do_add
        self._do_remove = do_remove
        self.item = item

    def redo(self):
        self._do_add(self.item)

    def undo(self):
        self._do_remove(self.item)


class DeleteItemsCommand(QUndoCommand):
    """Inverse of AddItemCommand, for one or more items at once (e.g. a
    multi-select Delete)."""

    def __init__(self, do_add, do_remove, items, text="Delete Component(s)"):
        super().__init__(text)
        self._do_add = do_add
        self._do_remove = do_remove
        self.items = list(items)

    def redo(self):
        for item in self.items:
            self._do_remove(item)

    def undo(self):
        for item in self.items:
            self._do_add(item)


class MoveItemCommand(QUndoCommand):
    """One completed drag (mouse press to release) of a single PlacedItem -
    pushed once per drag, not per intermediate mouse-move, so undo steps
    line up with what the user actually did."""

    def __init__(self, item: "PlacedItem", old_pos: QPointF, new_pos: QPointF, text="Move Component"):
        super().__init__(text)
        self.item = item
        self.old_pos = QPointF(old_pos)
        self.new_pos = QPointF(new_pos)

    def _apply(self, pos: QPointF):
        self.item.setPos(pos)
        self.item.model.x, self.item.model.y = from_scene_pos(pos)
        # Undo/redo of a move bypasses mouseReleaseEvent's own invalidation
        # (see there) - do it here too, since this changes the item's
        # keypoints just as much as the original drag did.
        if self.item.scene():
            for view in self.item.scene().views():
                if hasattr(view, "invalidate_points_edges_cache"):
                    view.invalidate_points_edges_cache()

    def redo(self):
        self._apply(self.new_pos)

    def undo(self):
        self._apply(self.old_pos)


class PropertyEditCommand(QUndoCommand):
    """One property-panel field edit. `apply_fn(item, value)` performs both
    the model mutation and whatever visual refresh that field needs (each
    field type's refresh differs - resize, re-rotate, brush re-sync, etc. -
    so the panel supplies it rather than this generic command knowing about
    every item type)."""

    def __init__(self, item, apply_fn, old_value, new_value, text="Edit Property"):
        super().__init__(text)
        self.item = item
        self.apply_fn = apply_fn
        self.old_value = old_value
        self.new_value = new_value

    def redo(self):
        self.apply_fn(self.item, self.new_value)

    def undo(self):
        self.apply_fn(self.item, self.old_value)


class CanvasView(QGraphicsView):
    # Which tags win when two would overlap (lower first).
    _TAG_PRIORITY = {"sink": 1, "source": 1, "button": 2, "led": 3, "sensor": 4, "belt": 5}

    def drawBackground(self, painter: QPainter, rect: QRectF):
        super().drawBackground(painter, rect)
        self._layout_tags()

    def _layout_tags(self):
        """Decide which canvas tags show, once per repaint: by priority
        (the selected items first, then devices, then belts), each only if
        it fits its item at this zoom and doesn't overlap one already
        placed (touching is fine)."""
        scale = math.sqrt(abs(self.transform().determinant())) or 1.0
        items = sorted(self.items_list, key=lambda i: (not i.isSelected(), self._TAG_PRIORITY.get(i.kind, 9)))
        placed = []
        for item in items:
            tag = getattr(item, "tag", None)
            if tag is None:
                continue
            tag.sync()
            show = tag._spec is not None and (item.isSelected() or item._tag_room(scale) >= tag._rect.width())
            if show:
                origin = self.mapFromScene(tag.scenePos())
                rect = tag._rect.translated(origin.x(), origin.y())
                if not item.isSelected() and any(rect.adjusted(1, 2, -1, -2).intersects(r) for r in placed):
                    show = False
                else:
                    placed.append(rect)
            if show != tag.shown:
                tag.shown = show
                tag.update()

    def __init__(self, scene: SnapGuideScene, items, on_items_changed=None, config=None):
        super().__init__(scene)
        self.items_list = items
        self.config = config
        self.on_items_changed = on_items_changed
        self.get_template: Optional[Callable[[str], Optional[ComponentTemplate]]] = None
        # The right-click menu (MainWindow._canvas_context_menu): called with
        # (global pos, scene pos, the component under the cursor or None).
        self.on_context_menu = None
        self._right_press_used = False      # a tool / the measure mode took this right-click
        self.on_mouse_moved: Optional[Callable[[float, float], None]] = None
        self._clipboard_models = []  # one or more deepcopy'd models - a group copy/paste
        self._last_mouse_scene_pos: Optional[QPointF] = None
        # Cache for _all_points_and_edges() - every item's keypoints/edges
        # only actually change when an item is added/removed or a property
        # edit resizes/moves one (see invalidate_points_edges_cache(), called
        # from those choke points), not on every single mouse-move pixel
        # that just reads this list for the hover coordinate snap.
        self._points_edges_cache: Optional[tuple] = None
        # Set externally by MainWindow once both exist. None (the
        # standalone-demo/no-undo case) falls back to applying mutations
        # directly instead of going through a command.
        self.undo_stack: Optional[QUndoStack] = None
        # An interactive drawing tool (path_tool.PathDrawTool) that gets
        # mouse/key events before the default select/drag handling.
        self.tool = None
        # Called first by Delete; returns True if it deleted something itself.
        self.on_delete_extra = None
        # Sketch lines on the clipboard too (layout_editor_cad.py): copies of
        # the selected ones, and how to paste them moved by (dx, dy).
        self.on_copy_extra = None
        self.on_paste_extra = None
        # Adds belt connections as an undo step (layout_editor_cad.py); unset,
        # a placed station's connections go straight into the config.
        self.on_add_connections = None
        self._clipboard_sketch = []
        self._pan_tool_active = False
        self._middle_pan_active = False
        self._middle_pan_last_pos = None
        # Measure tool: click a point (a keypoint/grid snap, like the live
        # coordinate readout) then a second point to measure length+angle;
        # click an existing component edge then a second edge to measure
        # the angle BETWEEN them instead - AutoCAD-style point-to-point
        # distance vs. line-to-line angle. `_measure_pending` is None, or
        # ("point"|"free", QPointF), or ("edge", (p1, p2)).
        self._measure_mode = False
        self._measure_pending: Optional[tuple] = None
        self.setAcceptDrops(True)
        self.setDragMode(QGraphicsView.RubberBandDrag)
        # Mouse-move events normally only arrive while a button is held -
        # tracking needs to be on (on the actual viewport widget, since
        # QGraphicsView delivers mouse events through it, not itself) to
        # get a live coordinate readout while just hovering, not dragging.
        self.setMouseTracking(True)
        self.viewport().setMouseTracking(True)
        self.setRenderHint(QPainter.Antialiasing)
        self.setTransformationAnchor(QGraphicsView.AnchorUnderMouse)
        half = self.CANVAS_EXTENT
        self.setSceneRect(QRectF(-half, -half, 2 * half, 2 * half))
        # Needed to actually receive key events (Ctrl+C/V, Delete) - a plain
        # QGraphicsView defaults to NoFocus.
        self.setFocusPolicy(Qt.StrongFocus)
        # MinimalViewportUpdate (the default) only repaints each moved/rotated
        # item's own old+new bounding box; the custom grid background redraw
        # for that patch can leave faint trailing artifacts, especially with
        # rotated (diamond-shaped) bounding regions. Full repaint avoids it -
        # a non-issue at this scene scale.
        self.setViewportUpdateMode(QGraphicsView.FullViewportUpdate)

    def dragEnterEvent(self, event):
        if event.mimeData().hasFormat("application/x-component-template"):
            event.acceptProposedAction()
        else:
            super().dragEnterEvent(event)

    def dragMoveEvent(self, event):
        if event.mimeData().hasFormat("application/x-component-template"):
            event.acceptProposedAction()
        else:
            super().dragMoveEvent(event)

    def dropEvent(self, event):
        mime = event.mimeData()
        if mime.hasFormat("application/x-component-template"):
            name = bytes(mime.data("application/x-component-template")).decode("utf-8")
            scene_pos = self.mapToScene(event.position().toPoint())
            self.place_template(name, *from_scene_pos(scene_pos))
            event.acceptProposedAction()
        else:
            super().dropEvent(event)

    def place_template(self, name: str, x: float, y: float, **overrides):
        """Place a new component from library template `name` at world (x, y)
        with a fresh id - what dropping it from the library does. `overrides`
        set model fields first (e.g. length=6, label="START"). Undoable.
        Returns the new item, or None for an unknown template."""
        template = self.get_template(name) if self.get_template else None
        if template is None:
            return None
        if template.entry is not None and template.entry.is_station:
            return self.place_station(template.entry, x, y)
        existing_ids = (i.model.id for i in self.items_list if i.kind == template.kind)
        model = template.factory(next_indexed_id(existing_ids, template.kind))
        for key, value in overrides.items():
            setattr(model, key, value)
        move_model(model, x - model.x, y - model.y)
        item_cls = ITEM_CLASS_FOR_KIND[template.kind]
        return self._add_item(item_cls(model), text=f"Add {template.kind}")

    def _fresh_id(self) -> Callable[[str, str], str]:
        """new_id(kind, old id): an id not yet used by that kind - also not
        by one handed out before from the same function."""
        taken = {}

        def new_id(kind: str, old: str) -> str:
            ids = taken.setdefault(kind, {i.model.id for i in self.items_list if i.kind == kind})
            fresh = old if old not in ids else unique_incremented_id(ids, old)
            ids.add(fresh)
            return fresh
        return new_id

    def place_station(self, entry: LibraryEntry, x: float, y: float) -> list:
        """Place every component of a station entry, centred on (x, y), with
        fresh ids and its links and belt connections pointing to the new
        copies - one undo step. Returns the new items, selected."""
        placed, connections = entry.place_station(self._fresh_id(), x, y)
        text = f"Add {entry.name}"
        if self.undo_stack is not None:
            self.undo_stack.beginMacro(text)
        items = [self._add_item(ITEM_CLASS_FOR_KIND[kind](model), text=text) for kind, model in placed]
        if connections:
            if self.on_add_connections is not None:
                self.on_add_connections(connections)
            elif self.config is not None:
                self.config.connections.extend(connections)
        if self.undo_stack is not None:
            self.undo_stack.endMacro()
        self.scene().clearSelection()
        for item in items:
            item.setSelected(True)
        return items

    def _do_add_item(self, item: PlacedItem) -> PlacedItem:
        """The actual add mutation - scene, items_list, config. Called
        directly (no undo stack) or as an AddItemCommand's redo/DeleteItems
        Command's undo."""
        self.scene().addItem(item)
        self.items_list.append(item)
        if self.config is not None:
            getattr(self.config, CONFIG_LIST_ATTR_FOR_KIND[item.kind]).append(item.model)
        self.invalidate_points_edges_cache()
        if self.on_items_changed:
            self.on_items_changed()
        return item

    def _do_remove_item(self, item: PlacedItem):
        """The actual remove mutation - inverse of `_do_add_item`."""
        self.scene().removeItem(item)
        self.items_list.remove(item)
        if self.config is not None:
            getattr(self.config, CONFIG_LIST_ATTR_FOR_KIND[item.kind]).remove(item.model)
        self.invalidate_points_edges_cache()
        if self.on_items_changed:
            self.on_items_changed()

    def _add_item(self, item: PlacedItem, text: str = "Add Component") -> PlacedItem:
        """Public add entry point: goes through the undo stack when one is
        attached, otherwise applies directly."""
        if self.undo_stack is not None:
            self.undo_stack.push(AddItemCommand(self._do_add_item, self._do_remove_item, item, text))
        else:
            self._do_add_item(item)
        return item

    def _remove_item(self, item: PlacedItem, text: str = "Delete Component"):
        """Public remove entry point - see `_add_item`."""
        if self.undo_stack is not None:
            self.undo_stack.push(DeleteItemsCommand(self._do_add_item, self._do_remove_item, [item], text))
        else:
            self._do_remove_item(item)

    # Scrolling room around any layout: without it the view can only scroll
    # within the items' bounds (and centres them when they fit), so a zoom
    # near the edge of the layout - or out - drifts away from the cursor.
    CANVAS_EXTENT = 1.0e7

    def wheelEvent(self, event):
        """Zoom about the cursor: the point under it stays under it."""
        if not event.angleDelta().y():
            return
        factor = 1.15 if event.angleDelta().y() > 0 else 1 / 1.15
        self.zoom_at(factor, event.position().toPoint())
        event.accept()

    def zoom_at(self, factor: float, pos=None):
        """Scale the view by `factor` keeping the scene point at viewport
        `pos` (default: the centre) where it is."""
        if pos is None:
            pos = self.viewport().rect().center()
        before = self.mapToScene(pos)
        anchor = self.transformationAnchor()
        self.setTransformationAnchor(QGraphicsView.NoAnchor)
        self.scale(factor, factor)
        self.setTransformationAnchor(anchor)
        # Scroll the scene point back under `pos` (the view scrolls: its
        # scroll bars, not the transform, place it).
        moved = self.mapFromScene(before) - pos
        self.horizontalScrollBar().setValue(self.horizontalScrollBar().value() + moved.x())
        self.verticalScrollBar().setValue(self.verticalScrollBar().value() + moved.y())

    def set_pan_mode(self, enabled: bool):
        """Toggle a persistent "Pan Tool" (left-click-drag always pans the
        view instead of selecting/rubber-banding) - the toggle-button
        equivalent of holding Space, for trackpad/one-button-mouse users
        who'd rather not hold a key down."""
        self._pan_tool_active = enabled
        self.setDragMode(QGraphicsView.ScrollHandDrag if enabled else QGraphicsView.RubberBandDrag)

    def set_measure_mode(self, enabled: bool):
        """Toggle the Measure Tool: while active, left-clicks select points
        (snapped to keypoints/grid) or existing component edges (at any
        angle) instead of selecting or dragging components."""
        self._measure_mode = enabled
        self._measure_pending = None
        if self.scene():
            self.scene().clear_measure_preview()
        self.setCursor(Qt.CrossCursor if enabled else Qt.ArrowCursor)

    def _measure_target_at(self, view_pos):
        raw_scene_pos = self.mapToScene(view_pos)
        points, edges = self._all_points_and_edges()
        return _find_measure_target(raw_scene_pos, points, edges, self._snap_tolerance_scene_units())

    def _draw_measure_selection(self, target):
        """Mark a just-clicked (now confirmed, not just hovered) target:
        a point marker, or - for an edge - nothing yet, since a single
        selected edge isn't meaningful on its own until a second one
        completes an angle measurement (drawn together in add_measure_angle)."""
        kind, value = target
        if kind != "edge":
            self.scene().add_measure_point(value)

    def _handle_measure_click(self, view_pos):
        target = self._measure_target_at(view_pos)
        kind, value = target

        if self._measure_pending is None:
            self._measure_pending = target
            self._draw_measure_selection(target)
            return

        prev_kind, prev_value = self._measure_pending
        prev_is_point = prev_kind in ("point", "free")
        this_is_point = kind in ("point", "free")

        if prev_is_point and this_is_point:
            # Point + point -> length (and angle-from-X-axis) between them.
            self._draw_measure_selection(target)
            self.scene().add_measure_line(prev_value, value)
            self._measure_pending = None
        elif prev_kind == "edge" and kind == "edge":
            # Edge + edge -> the angle BETWEEN the two lines.
            self.scene().add_measure_angle(prev_value, value)
            self._measure_pending = None
        else:
            # Mismatched types (e.g. a point was pending, but this click hit
            # an edge instead) - don't try to measure across types, just
            # restart fresh with whatever was actually just clicked.
            self._measure_pending = target
            self._draw_measure_selection(target)

    def keyPressEvent(self, event):
        if self.tool is not None and self.tool.key_press(event):
            event.accept()
            return
        # Don't fight the Pan Tool toggle: if it's already active, Space
        # has nothing to add (already in ScrollHandDrag), and releasing
        # Space later must not drop back to RubberBandDrag out from under it.
        if event.key() == Qt.Key_Space and not self._pan_tool_active:
            self.setDragMode(QGraphicsView.ScrollHandDrag)
        elif event.matches(QKeySequence.Copy):
            self._copy_selected()
        elif event.matches(QKeySequence.Cut):
            if self._copy_selected():
                self._delete_selected()
        elif event.matches(QKeySequence.Paste):
            self._paste_clipboard()
        elif event.key() in (Qt.Key_Delete, Qt.Key_Backspace):
            self._delete_selected()
        super().keyPressEvent(event)

    def keyReleaseEvent(self, event):
        if event.key() == Qt.Key_Space and not self._pan_tool_active:
            self.setDragMode(QGraphicsView.RubberBandDrag)
        super().keyReleaseEvent(event)

    def mousePressEvent(self, event):
        # Middle-mouse-drag pans regardless of the current tool/drag mode -
        # the same universal gesture CAD tools (AutoCAD, Fusion360) and
        # browsers use, so panning never requires switching tools or
        # holding Space at all.
        if event.button() == Qt.MiddleButton:
            self._middle_pan_active = True
            self._middle_pan_last_pos = event.pos()
            self.setCursor(Qt.ClosedHandCursor)
            event.accept()
            return
        self._right_press_used = False
        if self.tool is not None and self.tool.mouse_press(event):
            self._right_press_used = event.button() == Qt.RightButton
            event.accept()
            return
        if self._measure_mode and event.button() == Qt.LeftButton:
            self._handle_measure_click(event.pos())
            event.accept()
            return
        if self._measure_mode and event.button() == Qt.RightButton:
            # Cancel an in-progress selection - a point marker (if any)
            # stays on the canvas, it's just no longer waiting for a second
            # click to complete a measurement.
            self._measure_pending = None
            self._right_press_used = True
            event.accept()
            return
        super().mousePressEvent(event)

    def contextMenuEvent(self, event):
        """Right-click: a menu of quick commands for what is under the
        cursor (a component, or the empty canvas) - unless a running tool or
        the measure mode used the right button (end / cancel), as in a CAD
        tool."""
        used, self._right_press_used = self._right_press_used, False
        if used or self.tool is not None or self._measure_mode or self.on_context_menu is None:
            event.accept()
            return
        item = self.placed_item_at(event.pos())
        if item is not None and not item.isSelected():
            self.scene().clearSelection()
            item.setSelected(True)
        self.on_context_menu(event.globalPos(), self.mapToScene(event.pos()), item)
        event.accept()

    def placed_item_at(self, view_pos) -> Optional["PlacedItem"]:
        """The topmost component at a view position (a click on one of its
        child graphics counts), or None."""
        for graphic in self.items(view_pos):
            while graphic is not None and not isinstance(graphic, PlacedItem):
                graphic = graphic.parentItem()
            if graphic is not None:
                return graphic
        return None

    def _snap_tolerance_scene_units(self) -> float:
        scale = self.transform().m11()
        return SNAP_TOLERANCE_PX / scale if scale > 1e-6 else SNAP_TOLERANCE_PX

    def _all_points_and_edges(self):
        """Every placed item's keypoints/edges, in scene coords - the
        candidate set both the live coordinate readout and the measure
        tool snap free (non-dragged) points against.

        Cached across calls (see invalidate_points_edges_cache()) since this
        used to be recomputed - a full scan + mapToScene of every placed
        item - on every single mouse-move pixel while just hovering, not
        only while dragging."""
        if self._points_edges_cache is not None:
            return self._points_edges_cache
        points, edges = [], []
        for item in self.items_list:
            points.extend(item.mapToScene(p) for p in item._local_key_points())
            edges.extend((item.mapToScene(p1), item.mapToScene(p2)) for p1, p2 in item._local_edges())
        self._points_edges_cache = (points, edges)
        return self._points_edges_cache

    def invalidate_points_edges_cache(self):
        """Call whenever an item is added/removed or a property edit
        changes an item's geometry (resize, rotate, reposition via the
        properties panel) - anything that would make the cached list in
        _all_points_and_edges() stale. Deliberately NOT called on every
        drag-move; the item being dragged snapping against its own
        pre-drag position is an acceptable, self-correcting staleness that
        clears itself on the drag's next add/remove/property-edit."""
        self._points_edges_cache = None

    def mouseMoveEvent(self, event):
        self._last_mouse_scene_pos = self.mapToScene(event.pos())
        if self._measure_mode and self.scene():
            # Live "what would clicking here select" feedback - satisfies
            # the tool actually feeling "attached" to keypoints/grid/edges
            # rather than only revealing what it snapped to after the fact.
            self.scene().show_measure_preview(self._measure_target_at(event.pos()))
        if self.on_mouse_moved:
            points, edges = self._all_points_and_edges()
            snapped = _snap_free_point(self._last_mouse_scene_pos, points, edges, self._snap_tolerance_scene_units())
            world_x, world_y = from_scene_pos(snapped)
            self.on_mouse_moved(world_x, world_y)
        if self._middle_pan_active:
            pos = event.pos()
            delta = pos - self._middle_pan_last_pos
            self._middle_pan_last_pos = pos
            h_bar = self.horizontalScrollBar()
            v_bar = self.verticalScrollBar()
            h_bar.setValue(h_bar.value() - delta.x())
            v_bar.setValue(v_bar.value() - delta.y())
            event.accept()
            return
        if self.tool is not None and self.tool.mouse_move(event):
            event.accept()
            return
        super().mouseMoveEvent(event)

    def mouseReleaseEvent(self, event):
        if event.button() == Qt.MiddleButton and self._middle_pan_active:
            self._middle_pan_active = False
            self.unsetCursor()
            event.accept()
            return
        if self.tool is not None and self.tool.mouse_release(event):
            event.accept()
            return
        super().mouseReleaseEvent(event)

    def mouseDoubleClickEvent(self, event):
        if self.tool is not None and self.tool.mouse_double_click(event):
            event.accept()
            return
        super().mouseDoubleClickEvent(event)

    def _copy_selected(self) -> bool:
        """Ctrl+C (and the copy half of Ctrl+X): the selected components and
        sketch lines. False when nothing is selected (the clipboard is kept)."""
        selected = [i for i in self.scene().selectedItems() if isinstance(i, PlacedItem)]
        sketch = self.on_copy_extra() if self.on_copy_extra is not None else []
        if not selected and not sketch:
            return False
        self._clipboard_models = [deepcopy(i.model) for i in selected]
        self._clipboard_sketch = sketch
        return True

    def _paste_clipboard(self):
        if not self._clipboard_models and not self._clipboard_sketch:
            return
        if not self._clipboard_models:
            self._paste_sketch_only()
            return
        # Paste the whole group at the mouse position instead of the
        # original spot: shift every copied model by the same offset, from
        # the group's centroid to wherever the cursor currently is over the
        # canvas, so the copied items keep their layout relative to each
        # other but land where the user is pointing, not stacked on top of
        # the originals. Falls back to the old "nudge by half a unit" if
        # the mouse has never been over the canvas yet (e.g. paste
        # triggered before any mouse movement was recorded).
        cx = sum(model.x for model in self._clipboard_models) / len(self._clipboard_models)
        cy = sum(model.y for model in self._clipboard_models) / len(self._clipboard_models)
        if self._last_mouse_scene_pos is not None:
            target_x, target_y = from_scene_pos(self._last_mouse_scene_pos)
        else:
            target_x, target_y = cx + 0.5, cy + 0.5
        offset_x, offset_y = target_x - cx, target_y - cy

        multi = len(self._clipboard_models) > 1
        text = f"Paste {len(self._clipboard_models)} Components" if multi else "Paste Component"
        with_sketch = bool(self._clipboard_sketch and self.on_paste_extra is not None)
        if self.undo_stack is not None and (multi or with_sketch):
            self.undo_stack.beginMacro(text + (" and sketch" if with_sketch else ""))
        # Fresh ids first, then the links among the pasted ones (a turntable
        # and its platform belt) point to the copies; links to the rest of
        # the layout stay as they are.
        copies = [(KIND_FOR_MODEL_CLASS[type(m)], deepcopy(m)) for m in self._clipboard_models]
        id_map = {}
        for kind, new_model in copies:
            existing_ids = {i.model.id for i in self.items_list if i.kind == kind}
            existing_ids |= {new for (k, _), new in id_map.items() if k == kind}
            old_id = new_model.id
            new_model.id = unique_incremented_id(existing_ids, old_id)
            id_map[(kind, old_id)] = new_model.id
        new_items = []
        for kind, new_model in copies:
            remap_references(kind, new_model, id_map)
            move_model(new_model, offset_x, offset_y)
            item_cls = ITEM_CLASS_FOR_KIND[kind]
            new_items.append(self._add_item(item_cls(new_model), text=text))
        if with_sketch:
            self.on_paste_extra(self._clipboard_sketch, offset_x, offset_y)   # moved along with the components
        if self.undo_stack is not None and (multi or with_sketch):
            self.undo_stack.endMacro()

        self.scene().clearSelection()
        for item in new_items:
            item.setSelected(True)

    def _paste_sketch_only(self):
        """Ctrl+V with only sketch lines on the clipboard: their centre at the
        mouse (else half a metre on)."""
        if self.on_paste_extra is None:
            return
        pts = [p for e in self._clipboard_sketch for p in e.points]
        cx, cy = sum(x for x, _ in pts) / len(pts), sum(y for _, y in pts) / len(pts)
        if self._last_mouse_scene_pos is not None:
            tx, ty = from_scene_pos(self._last_mouse_scene_pos)
        else:
            tx, ty = cx + 0.5, cy + 0.5
        self.on_paste_extra(self._clipboard_sketch, tx - cx, ty - cy)

    def _delete_selected(self):
        selected = [i for i in self.scene().selectedItems() if isinstance(i, PlacedItem)]
        # Components and sketch lines selected together go together, one undo step.
        macro = self.undo_stack is not None and bool(selected) and self.on_delete_extra is not None
        if macro:
            self.undo_stack.beginMacro("Delete")
        if self.on_delete_extra is not None:
            self.on_delete_extra()       # the selected sketch entities (layout_editor_cad.py)
        if selected:
            # One combined command for the whole selection, not one per item -
            # a multi-select delete should undo as a single step.
            if self.undo_stack is not None:
                text = "Delete Component" if len(selected) == 1 else f"Delete {len(selected)} Components"
                self.undo_stack.push(DeleteItemsCommand(self._do_add_item, self._do_remove_item, selected, text))
            else:
                for item in selected:
                    self._do_remove_item(item)
        if macro:
            self.undo_stack.endMacro()


