SCALE = 50.0  # px per "meter" - arbitrary for this prototype, not tied to the real world scale
GRID_SIZE = 50
SNAP_TOLERANCE_PX = 14.0  # in VIEW pixels, converted to scene units by current zoom


def to_scene_pos(world_x: float, world_y: float) -> QPointF:
    """World (X right, Y up) -> Qt scene (X right, Y down)."""
    return QPointF(world_x * SCALE, -world_y * SCALE)


def from_scene_pos(scene_pos: QPointF) -> tuple[float, float]:
    """Qt scene (X right, Y down) -> world (X right, Y up)."""
    return scene_pos.x() / SCALE, -scene_pos.y() / SCALE


def arc_ring_points(radius: float, start_angle_deg: float, end_angle_deg: float, thickness: float):
    """Ring-segment outline (outer edge start->end, then inner edge back
    end->start) centered at the local origin - the arc-belt equivalent of a
    rectangle's 4 corners. Same Y-up, un-scaled local convention as
    everything else; caller applies SCALE and the Y-flip. Mirrors
    visualizer.py's draw_belt curved-segment approach."""
    angle_diff = end_angle_deg - start_angle_deg
    if angle_diff <= 0:
        angle_diff += 360.0
    segments = max(8, int(angle_diff / 6))
    inner_r = max(0.0, radius - thickness / 2.0)
    outer_r = radius + thickness / 2.0
    points = []
    for i in range(segments + 1):
        a = math.radians(start_angle_deg + angle_diff * i / segments)
        points.append((outer_r * math.cos(a), outer_r * math.sin(a)))
    for i in range(segments, -1, -1):
        a = math.radians(start_angle_deg + angle_diff * i / segments)
        points.append((inner_r * math.cos(a), inner_r * math.sin(a)))
    return points


_HV_EDGE_EPS = 1e-2  # scene units - an edge within this of perfectly H/V counts as aligned


def _rotate_vec(v: QPointF, angle_deg: float) -> QPointF:
    """Rotate a vector (or point, treated as a vector from the origin) by
    angle_deg, using the same rotation convention as QGraphicsItem.setRotation
    (Qt's CW-positive-on-screen). Used to work in a frame aligned to an
    item's own rotation instead of world X/Y - see _snap's Pass 1b."""
    return QTransform().rotate(angle_deg).map(v)


def _classify_hv_edge(p1: QPointF, p2: QPointF):
    """Classify an edge as vertical ('v', x, y_lo, y_hi) or horizontal
    ('h', y, x_lo, x_hi) in WHATEVER frame p1/p2 are already expressed in,
    or None if it's at any other angle in that frame. Called directly on
    scene-space points for world H/V matching, or on points pre-rotated via
    `_rotate_vec` to check alignment against some other reference angle
    (e.g. a rotated belt's own angle - see _snap's Pass 1b)."""
    if abs(p1.x() - p2.x()) < _HV_EDGE_EPS:
        return ("v", p1.x(), min(p1.y(), p2.y()), max(p1.y(), p2.y()))
    if abs(p1.y() - p2.y()) < _HV_EDGE_EPS:
        return ("h", p1.y(), min(p1.x(), p2.x()), max(p1.x(), p2.x()))
    return None


def _snap_free_point(scene_pos: QPointF, points, edges, tolerance: float) -> QPointF:
    """Snap a bare scene point (no dragged item, no anchor/rotation/ortho
    involved) to the nearest matching keypoint/edge on each axis
    independently, falling back to the grid - the same priority order as
    PlacedItem._snap's passes 2-4, simplified since there's no "coherent
    pair"/rotated-frame concept to apply without an actual item being
    moved. Used for the live cursor-coordinate readout, so hovering near a
    component or grid line shows the coordinate you'd actually land on."""
    best_dx, best_dx_dist = 0.0, tolerance
    best_dy, best_dy_dist = 0.0, tolerance
    for p in points:
        dx = p.x() - scene_pos.x()
        if abs(dx) < best_dx_dist:
            best_dx_dist, best_dx = abs(dx), dx
        dy = p.y() - scene_pos.y()
        if abs(dy) < best_dy_dist:
            best_dy_dist, best_dy = abs(dy), dy
    for p1, p2 in edges:
        classified = _classify_hv_edge(p1, p2)
        if classified is None:
            continue
        kind, value, _lo, _hi = classified
        if kind == "v":
            dx = value - scene_pos.x()
            if abs(dx) < best_dx_dist:
                best_dx_dist, best_dx = abs(dx), dx
        else:
            dy = value - scene_pos.y()
            if abs(dy) < best_dy_dist:
                best_dy_dist, best_dy = abs(dy), dy
    if best_dx_dist >= tolerance:
        grid_x = round(scene_pos.x() / GRID_SIZE) * GRID_SIZE
        dx = grid_x - scene_pos.x()
        if abs(dx) < tolerance:
            best_dx = dx
    if best_dy_dist >= tolerance:
        grid_y = round(scene_pos.y() / GRID_SIZE) * GRID_SIZE
        dy = grid_y - scene_pos.y()
        if abs(dy) < tolerance:
            best_dy = dy
    return QPointF(scene_pos.x() + best_dx, scene_pos.y() + best_dy)


def _point_segment_distance(p: QPointF, a: QPointF, b: QPointF) -> float:
    """Shortest distance from p to the segment a-b (not the infinite line -
    clamped to the segment's own endpoints), for ANY angle - unlike
    _classify_hv_edge/_snap_free_point, which are deliberately scoped to
    horizontal/vertical only for the drag-alignment system."""
    dx, dy = b.x() - a.x(), b.y() - a.y()
    length_sq = dx * dx + dy * dy
    if length_sq < 1e-9:
        return math.hypot(p.x() - a.x(), p.y() - a.y())
    t = max(0.0, min(1.0, ((p.x() - a.x()) * dx + (p.y() - a.y()) * dy) / length_sq))
    closest = QPointF(a.x() + t * dx, a.y() + t * dy)
    return math.hypot(p.x() - closest.x(), p.y() - closest.y())


def _find_measure_target(scene_pos: QPointF, points, edges, tolerance: float):
    """What a measure-tool click/hover at `scene_pos` would select: a
    keypoint ('point', QPointF), an existing component edge at ANY angle
    ('edge', (p1, p2)) - not H/V-restricted, since measuring the angle
    between two arbitrarily-rotated belts is exactly the point - or,
    failing both, wherever it'd land after grid-snapping ('free', QPointF).
    Points win ties over edges (same priority as the drag-alignment system),
    and only a genuinely nearby point ends the search early - an edge is
    only considered when no point is close enough."""
    best_point, best_point_dist = None, tolerance
    for p in points:
        d = math.hypot(p.x() - scene_pos.x(), p.y() - scene_pos.y())
        if d < best_point_dist:
            best_point_dist, best_point = d, p
    if best_point is not None:
        return ("point", best_point)

    best_edge, best_edge_dist = None, tolerance
    for p1, p2 in edges:
        d = _point_segment_distance(scene_pos, p1, p2)
        if d < best_edge_dist:
            best_edge_dist, best_edge = d, (p1, p2)
    if best_edge is not None:
        return ("edge", best_edge)

    return ("free", _snap_free_point(scene_pos, [], [], tolerance))


