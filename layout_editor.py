    def _on_shape_finished(self, points: list[QPointF]):
        self._raw_points = points
        self.save_btn.setEnabled(True)
        mode = self.mode_combo.currentText()
        cx = sum(p.x() for p in points) / len(points)
        cy = sum(p.y() for p in points) / len(points)
        spins = None
        if mode == "Triangle" and len(points) == 3:
            spins = self.tri_spins
        elif mode == "Quadrilateral" and len(points) == 4:
            spins = self.quad_spins
        if spins:
            for (x_spin, y_spin), p in zip(spins, points):
                x_spin.blockSignals(True)
                y_spin.blockSignals(True)
                x_spin.setValue((p.x() - cx) / SCALE)
                y_spin.setValue(-(p.y() - cy) / SCALE)
                x_spin.blockSignals(False)
                y_spin.blockSignals(False)

    def _on_arc_finished(self, center: QPointF, edge: QPointF):
        dx, dy = edge.x() - center.x(), edge.y() - center.y()
        radius_px = math.hypot(dx, dy)
        end_angle = math.degrees(math.atan2(-dy, dx))
        if end_angle < 0:
            end_angle += 360.0
        self.arc_radius_spin.blockSignals(True)
        self.arc_end_spin.blockSignals(True)
        self.arc_radius_spin.setValue(radius_px / SCALE)
        self.arc_end_spin.setValue(end_angle)
        self.arc_radius_spin.blockSignals(False)
        self.arc_end_spin.blockSignals(False)
        self._apply_arc_params()

    # ---- parameters -> preview ----

    def _apply_triangle_params(self):
        self._set_scene_points_from_meters([(x.value(), y.value()) for x, y in self.tri_spins])

    def _apply_quad_params(self):
        self._set_scene_points_from_meters([(x.value(), y.value()) for x, y in self.quad_spins])

    def _set_scene_points_from_meters(self, points_m):
        scene_points = [QPointF(x * SCALE, -y * SCALE) for x, y in points_m]
        self.draw_view.set_preview_points(scene_points)
        self._raw_points = scene_points
        self.save_btn.setEnabled(True)

    def _apply_arc_params(self):
        radius_px = self.arc_radius_spin.value() * SCALE
        thickness_px = self.arc_thickness_spin.value() * SCALE
        # Preview centered at the canvas origin - only radius/angles/
        # thickness are saved, the placed position comes from the drop.
        self.draw_view.set_preview_arc(
            QPointF(0, 0), radius_px, self.arc_start_spin.value(), self.arc_end_spin.value(), thickness_px
        )
        self.save_btn.setEnabled(True)

    def _pick_color(self):
        chosen = QColorDialog.getColor(QColor(self._color), self, "Template Color")
        if chosen.isValid():
            self._color = chosen.name()
            self.color_btn.setStyleSheet(f"background-color:{self._color};")
            self.color_btn.setText(self._color)

    def _on_save(self):
        name = self.name_edit.text().strip()
        if not name:
            return
        speed = self.speed_spin.value()
        direction = self.direction_spin.value()
        color = self._color
        mode = self.mode_combo.currentText()

        if mode == "Arc":
            radius = self.arc_radius_spin.value()
            start_angle = self.arc_start_spin.value()
            end_angle = self.arc_end_spin.value()
            thickness = self.arc_thickness_spin.value()

            def factory(new_id: str) -> Belt:
                return Belt(
                    id=new_id, type="curved", shape="arc",
                    x=0.0, y=0.0, length=0.0, beltWidth=thickness, rotation=0.0,
                    radius=radius, startAngle=start_angle, endAngle=end_angle,
                    speed=speed, directionAngle=direction, color=color,
                )

            self.result_template = ComponentTemplate(name=name, kind="belt", factory=factory, removable=True)
            self.accept()
            return

        if not self._raw_points:
            return
        pts = self._raw_points
        cx = sum(p.x() for p in pts) / len(pts)
        cy = sum(p.y() for p in pts) / len(pts)
        # Local vertices in meters, Y-up (same convention as world/scene).
        vertexs = [{"x": (p.x() - cx) / SCALE, "y": -(p.y() - cy) / SCALE} for p in pts]
        xs = [v["x"] for v in vertexs]
        ys = [v["y"] for v in vertexs]
        length = max(xs) - min(xs) or 1.0
        belt_width = max(ys) - min(ys) or 1.0

        def factory(new_id: str) -> Belt:
            return Belt(
                id=new_id, type="linear", shape="quadrilateral",
                x=0.0, y=0.0, length=length, beltWidth=belt_width, rotation=0.0,
                speed=speed, directionAngle=direction, color=color,
                vertexs=[dict(v) for v in vertexs],
            )

        self.result_template = ComponentTemplate(name=name, kind="belt", factory=factory, removable=True)
        self.accept()


