class SnapGuideScene(QGraphicsScene):
    """QGraphicsScene that also owns the temporary alignment-guide overlay
    (dashed lines through the aligned coordinate, plus a dot at every
    sibling key point considered during the current drag)."""

    def __init__(self):
        super().__init__(-4000, -4000, 8000, 8000)
        self.setBackgroundBrush(QBrush(QColor(30, 30, 30)))
        self._guide_items = []
        # Set externally by MainWindow once both exist - lets PlacedItem
        # push a MoveItemCommand when a drag completes without needing a
        # direct reference to MainWindow itself.
        self.undo_stack: Optional["QUndoStack"] = None
        # Called with the list of items a drag just moved, inside that drag's
        # undo macro - layout_editor_cad.py uses it to keep belt connections.
        self.on_items_moved: Optional[Callable[[list], None]] = None
        # Persistent measure-tool markers/lines/labels - separate from
        # _guide_items (the transient per-drag alignment overlay, cleared on
        # every mouse release) since these should stick around until the
        # user explicitly clears them.
        self._measure_items = []
        # Live "what would clicking here select right now" hover preview -
        # separate again, redrawn on every mouse move while the measure
        # tool is active and cleared independently of the persistent
        # measurements/drag-alignment overlays.
        self._measure_preview_items = []

    def add_measure_point(self, scene_pos: QPointF) -> None:
        """A single marker point (CAD "marker point" tool) - a small cross
        plus a label showing its world-space position."""
        color = QColor(0, 220, 255)
        size = 6
        h_line = self.addLine(scene_pos.x() - size, scene_pos.y(), scene_pos.x() + size, scene_pos.y(), QPen(color, 2))
        v_line = self.addLine(scene_pos.x(), scene_pos.y() - size, scene_pos.x(), scene_pos.y() + size, QPen(color, 2))
        wx, wy = from_scene_pos(scene_pos)
        label = self.addText(f"({wx:.2f}, {wy:.2f})")
        label.setDefaultTextColor(color)
        label.setPos(scene_pos.x() + size + 2, scene_pos.y() - size - 2)
        for item in (h_line, v_line, label):
            item.setZValue(2000)
            self._measure_items.append(item)

    def add_measure_line(self, start_scene: QPointF, end_scene: QPointF) -> None:
        """A marker line between two already-marked points (CAD "marker
        line" / measure tool) - draws the connecting line and labels it
        with the length (world units) and angle (degrees, CCW from +X,
        matching this app's world convention elsewhere - e.g. belt
        rotation/directionAngle)."""
        color = QColor(0, 220, 255)
        line = self.addLine(start_scene.x(), start_scene.y(), end_scene.x(), end_scene.y(), QPen(color, 2, Qt.SolidLine))
        line.setZValue(2000)
        self._measure_items.append(line)

        wx1, wy1 = from_scene_pos(start_scene)
        wx2, wy2 = from_scene_pos(end_scene)
        length = math.hypot(wx2 - wx1, wy2 - wy1)
        angle = math.degrees(math.atan2(wy2 - wy1, wx2 - wx1))
        mid = QPointF((start_scene.x() + end_scene.x()) / 2.0, (start_scene.y() + end_scene.y()) / 2.0)
        # Plain ASCII only - a Windows console's default cp1252 codepage
        # can't encode Greek theta, and this text has no reason to risk
        # hitting that the way a stray future debug print/log call could.
        label = self.addText(f"L={length:.3f}  angle={angle:.1f} deg")
        label.setDefaultTextColor(color)
        label.setPos(mid.x() + 6, mid.y() - 20)
        label.setZValue(2000)
        self._measure_items.append(label)

    def add_measure_angle(self, line1, line2) -> None:
        """CAD "select line and line to measure angle": highlights both
        selected edges (their real segments, at whatever angle they're
        actually at - not H/V-restricted the way drag-alignment edges are)
        and labels the angle between their directions, normalized to
        [0, 180] degrees (the angle BETWEEN two lines has no inherent
        direction/sign, unlike a point-to-point measure line's angle)."""
        color = QColor(255, 160, 0)
        p1a, p1b = line1
        p2a, p2b = line2
        seg1 = self.addLine(p1a.x(), p1a.y(), p1b.x(), p1b.y(), QPen(color, 3))
        seg2 = self.addLine(p2a.x(), p2a.y(), p2b.x(), p2b.y(), QPen(color, 3))
        seg1.setZValue(2000)
        seg2.setZValue(2000)
        self._measure_items.append(seg1)
        self._measure_items.append(seg2)

        wx1a, wy1a = from_scene_pos(p1a)
        wx1b, wy1b = from_scene_pos(p1b)
        wx2a, wy2a = from_scene_pos(p2a)
        wx2b, wy2b = from_scene_pos(p2b)
        angle1 = math.degrees(math.atan2(wy1b - wy1a, wx1b - wx1a))
        angle2 = math.degrees(math.atan2(wy2b - wy2a, wx2b - wx2a))
        diff = abs(angle1 - angle2) % 360.0
        if diff > 180.0:
            diff = 360.0 - diff

        mid = QPointF(
            (p1a.x() + p1b.x() + p2a.x() + p2b.x()) / 4.0,
            (p1a.y() + p1b.y() + p2a.y() + p2b.y()) / 4.0,
        )
        label = self.addText(f"angle between lines={diff:.1f} deg")
        label.setDefaultTextColor(color)
        label.setPos(mid.x() + 6, mid.y() - 20)
        label.setZValue(2000)
        self._measure_items.append(label)

    def clear_measurements(self) -> None:
        for item in self._measure_items:
            self.removeItem(item)
        self._measure_items.clear()

    def show_measure_preview(self, target) -> None:
        """Live hover feedback for the measure tool: a dim marker over
        whatever a click right now would select - a small ring on an exact
        keypoint, a highlighted segment over a candidate edge, or a plain
        cross for a grid-snapped/free point. Mirrors the drag-alignment
        system's capture highlight, but as a hover PREVIEW (nothing is
        selected yet) rather than a confirmed snap."""
        self.clear_measure_preview()
        if target is None:
            return
        kind, value = target
        preview_color = QColor(0, 220, 255, 160)
        if kind == "edge":
            p1, p2 = value
            seg = self.addLine(p1.x(), p1.y(), p2.x(), p2.y(), QPen(preview_color, 3))
            seg.setZValue(1999)
            self._measure_preview_items.append(seg)
        else:
            ring = self.addEllipse(value.x() - 6, value.y() - 6, 12, 12, QPen(preview_color, 2), QBrush(Qt.NoBrush))
            ring.setZValue(1999)
            self._measure_preview_items.append(ring)

    def clear_measure_preview(self) -> None:
        for item in self._measure_preview_items:
            self.removeItem(item)
        self._measure_preview_items.clear()

    def drawBackground(self, painter: QPainter, rect: QRectF):
        super().drawBackground(painter, rect)
        painter.setPen(QPen(QColor(55, 55, 55), 0))
        left = int(rect.left()) - (int(rect.left()) % GRID_SIZE)
        top = int(rect.top()) - (int(rect.top()) % GRID_SIZE)
        x = left
        while x < rect.right():
            painter.drawLine(x, rect.top(), x, rect.bottom())
            x += GRID_SIZE
        y = top
        while y < rect.bottom():
            painter.drawLine(rect.left(), y, rect.right(), y)
            y += GRID_SIZE
        # Origin axes
        painter.setPen(QPen(QColor(150, 60, 60), 0))
        painter.drawLine(0, rect.top(), 0, rect.bottom())
        painter.setPen(QPen(QColor(60, 150, 60), 0))
        painter.drawLine(rect.left(), 0, rect.right(), 0)

    def show_guides(self, v_xs, h_ys, anchor_point=None, x_highlight=None, y_highlight=None):
        """Draws just what's relevant to the ONE active anchor keypoint (the
        dragged item's own keypoint nearest the mouse cursor - see
        PlacedItem._snap): a small marker at the anchor itself, plus at most
        one highlight per axis for whatever it's actually aligning to.
        Deliberately does NOT mark every nearby sibling keypoint - showing
        every candidate in range at once was the "too many pairs highlighted"
        clutter this replaces."""
        self.clear_guides()
        object_pen = QPen(QColor(255, 60, 200), 0, Qt.DashLine)
        grid_pen = QPen(QColor(80, 180, 255), 0, Qt.DashLine)
        x_pen = grid_pen if x_highlight and x_highlight[0] == "grid" else object_pen
        y_pen = grid_pen if y_highlight and y_highlight[0] == "grid" else object_pen
        for x in v_xs:
            line = self.addLine(x, -4000, x, 4000, x_pen)
            line.setZValue(1000)
            self._guide_items.append(line)
        for y in h_ys:
            line = self.addLine(-4000, y, 4000, y, y_pen)
            line.setZValue(1000)
            self._guide_items.append(line)
        if anchor_point is not None:
            anchor_pen = QPen(QColor(255, 220, 0), 0)
            anchor_brush = QBrush(QColor(255, 220, 0))
            dot = self.addEllipse(anchor_point.x() - 3, anchor_point.y() - 3, 6, 6, anchor_pen, anchor_brush)
            dot.setZValue(1001)
            self._guide_items.append(dot)
        # Whatever the anchor is actually aligning to (at most one per axis,
        # since the anchor is a single point/edge on each side) gets a
        # louder highlight - a ring+dot for a point target, or a thick
        # segment over the real edge span for an edge target.
        for highlight in (x_highlight, y_highlight):
            self._draw_capture_highlight(highlight)

    def _draw_capture_highlight(self, highlight):
        if highlight is None:
            return
        kind = highlight[0]
        color = QColor(0, 255, 160)
        if kind == "point":
            p = highlight[1]
            ring = self.addEllipse(p.x() - 7, p.y() - 7, 14, 14, QPen(color, 2), QBrush(Qt.NoBrush))
            ring.setZValue(1002)
            self._guide_items.append(ring)
            core_dot = self.addEllipse(p.x() - 3, p.y() - 3, 6, 6, QPen(Qt.NoPen), QBrush(color))
            core_dot.setZValue(1002)
            self._guide_items.append(core_dot)
        elif kind == "edge":
            p1, p2 = highlight[1], highlight[2]
            segment = self.addLine(p1.x(), p1.y(), p2.x(), p2.y(), QPen(color, 4))
            segment.setZValue(1002)
            self._guide_items.append(segment)

    def clear_guides(self):
        for item in self._guide_items:
            self.removeItem(item)
        self._guide_items.clear()


class PlacedItem(QGraphicsPolygonItem):
    """Shared behavior for anything placed on the canvas: key-point capture
    (works for any polygon, so both rectangles and custom drawn shapes get
    correct rotation-aware alignment), zoom-independent drag-to-snap, and
    keeping `self.model` in sync with the Qt item's position/rotation."""

    kind = "item"  # overridden by subclasses

    def __init__(self, model, local_points: list[QPointF]):
        super().__init__(QPolygonF(local_points))
        self.model = model
        # Only snap (and show guide lines/points) while the user is actually
        # dragging with the mouse - not for programmatic setPos() calls
        # coming from the properties panel, which should apply the typed
        # value literally. Must be set before setFlags()/setPos() below,
        # since those can trigger itemChange() immediately.
        self._dragging = False
        # Updated on every press/move while dragging - the current mouse
        # position in scene coordinates, used to pick which one of this
        # item's own keypoints is the active alignment "anchor" (see
        # _snap): whichever keypoint is closest to the mouse right now.
        self._drag_mouse_scene_pos = None
        # This item's own pos() at the start of the current drag - used to
        # decide whether a MoveItemCommand is worth pushing on release (and
        # what its "old" position was).
        self._drag_start_item_pos = None
        # Ortho mode (see _apply_ortho_constraint): whether Shift was held
        # as of the most recent press/move event during the current drag.
        self._drag_shift_held = False
        # Set by _apply_ortho_constraint to "x" or "y" (the axis currently
        # held at the drag-start value) or None - read by _snap so object/
        # grid snapping never overrides an active ortho lock.
        self._ortho_locked_axis: Optional[str] = None
        # Which axis is free to move ("x" or "y"), decided once on the
        # first move of a continuous Shift-hold and latched from then on -
        # see _apply_ortho_constraint for why it isn't re-decided every move.
        self._ortho_free_axis: Optional[str] = None
        # Set by itemChange() to whatever correction _snap() just applied on
        # top of the raw candidate position (may be (0,0)) - read right
        # after super().mouseMoveEvent() returns so that same correction can
        # be applied to the rest of a multi-selection too (see
        # mouseMoveEvent: only the item actually under the cursor gets
        # `_dragging=True` and runs _snap, so without this the rest of the
        # group would be left at Qt's raw, unsnapped multi-drag position).
        self._pending_group_correction: Optional[QPointF] = None
        # Snapshot of _sibling_key_points()/_sibling_edges(), taken once at
        # the start of a drag and reused for every itemChange() during it,
        # instead of rescanning the whole scene on every single mouse-move
        # pixel. Valid siblings (non-selected items - see
        # _is_valid_alignment_sibling) never move during someone else's
        # drag, so their geometry is safe to cache for the drag's duration;
        # cleared at mouseReleaseEvent so the next drag starts fresh.
        self._cached_sibling_points: Optional[list] = None
        self._cached_sibling_edges: Optional[list] = None
        self.setFlags(
            QGraphicsItem.ItemIsMovable
            | QGraphicsItem.ItemIsSelectable
            | QGraphicsItem.ItemSendsGeometryChanges
        )
        self.setPos(to_scene_pos(model.x, model.y))
        # Sink has no `rotation` field at all (matches the pygame app: sinks
        # are always drawn upright), so default to 0 rather than crashing.
        self.setRotation(-getattr(model, "rotation", 0.0))

    def _local_key_points(self):
        """4+ corners (polygon vertices), their edge midpoints, and the
        centroid - in local (unrotated) coordinates. Works for any N-gon,
        so a plain rectangle and a freehand custom shape both get correct,
        uniform alignment key points."""
        pts = list(self.polygon())
        if not pts:
            return [QPointF(0, 0)]
        n = len(pts)
        key_points = list(pts)
        for i in range(n):
            a, b = pts[i], pts[(i + 1) % n]
            key_points.append(QPointF((a.x() + b.x()) / 2.0, (a.y() + b.y()) / 2.0))
        cx = sum(p.x() for p in pts) / n
        cy = sum(p.y() for p in pts) / n
        key_points.append(QPointF(cx, cy))
        return key_points

    def _key_points_at(self, candidate_pos: QPointF):
        """Scene-space key points this item would have if its position were
        `candidate_pos` and its rotation were unchanged - i.e. what
        mapToScene() would return without actually moving the item yet.
        Rotation-aware, so this works correctly for tilted items (plain
        center +/- half-width/height bounding-box math does not)."""
        transform = QTransform().rotate(self.rotation())
        return [transform.map(p) + candidate_pos for p in self._local_key_points()]

    def _local_edges(self):
        """Consecutive polygon-vertex pairs, in local (unrotated)
        coordinates - the edges considered for point-to-edge and
        edge-to-edge alignment, alongside `_local_key_points`'s corners/
        midpoints/center."""
        pts = list(self.polygon())
        n = len(pts)
        if n < 2:
            return []
        return [(pts[i], pts[(i + 1) % n]) for i in range(n)]

    def _edges_at(self, candidate_pos: QPointF):
        """Scene-space edges this item would have at `candidate_pos`,
        rotation-aware like `_key_points_at`."""
        transform = QTransform().rotate(self.rotation())
        return [
            (transform.map(p1) + candidate_pos, transform.map(p2) + candidate_pos)
            for p1, p2 in self._local_edges()
        ]

    def _is_valid_alignment_sibling(self, other) -> bool:
        """Whether `other` should be considered an alignment target for
        `self`'s drag. Excludes `other.isSelected()` items - during a
        multi-select drag, every other selected item is ALSO being moved
        this same frame (see mouseMoveEvent's group-correction propagation
        to every other selected item), so treating one as a snap target for
        another means trying to align the group onto itself: as a
        follower's position shifts each frame in lockstep with the leader,
        its distance to the leader's anchor crosses the snap tolerance
        unpredictably, which is exactly what caused "random jump" glitches
        during group drags. A solo drag has no other selected items, so
        this never changes single-item behavior."""
        return isinstance(other, PlacedItem) and other is not self and not other.isSelected()

    def _sibling_edges(self):
        edges = []
        if not self.scene():
            return edges
        for other in self.scene().items():
            if not self._is_valid_alignment_sibling(other):
                continue
            for p1, p2 in other._local_edges():
                edges.append((other.mapToScene(p1), other.mapToScene(p2)))
        return edges

    def _sibling_key_points(self):
        points = []
        if not self.scene():
            return points
        for other in self.scene().items():
            if not self._is_valid_alignment_sibling(other):
                continue
            for p in other._local_key_points():
                points.append(other.mapToScene(p))
        return points

    def _snap_tolerance_scene_units(self) -> float:
        views = self.scene().views() if self.scene() else []
        if views:
            scale = views[0].transform().m11()
            if scale > 1e-6:
                return SNAP_TOLERANCE_PX / scale
        return SNAP_TOLERANCE_PX

    def _snap(self, candidate_pos: QPointF, sibling_points, sibling_edges, locked_axis: Optional[str] = None):
        # Only ONE of my own keypoints is "live" at a time - whichever is
        # closest to the mouse cursor right now (the point the user is
        # conceptually holding) - rather than checking all of my corners/
        # midpoints/center against every sibling simultaneously.
        #
        # `locked_axis` ("x", "y", or None) comes from ortho mode - when
        # set, that axis is held at its ortho-constrained value and none of
        # the passes below are allowed to move it, even if a coherent match
        # is found there; only the free axis remains eligible for snapping.
        tolerance = self._snap_tolerance_scene_units()
        my_points = self._key_points_at(candidate_pos)
        mouse_pos = self._drag_mouse_scene_pos
        if mouse_pos is None:
            anchor = my_points[0]
        else:
            anchor = min(
                my_points,
                key=lambda p: (p.x() - mouse_pos.x()) ** 2 + (p.y() - mouse_pos.y()) ** 2,
            )

        best_dx, best_dx_dist, x_highlight = 0.0, tolerance, None
        best_dy, best_dy_dist, y_highlight = 0.0, tolerance, None
        x_free = locked_axis != "x"
        y_free = locked_axis != "y"

        # Pass 1: prefer ONE coherent point-to-point match, close on BOTH
        # axes at once, over independently matching X to one sibling and Y
        # to a different one. The latter can "tear" a tight cluster of
        # nearby corners apart even though each axis is individually within
        # tolerance - e.g. several short, identically-rotated belt segments
        # chained end to end (test_config.json's belt_1_2_2/3/4 are 0.4m
        # segments all at 30 degrees, a few cm apart): with independent
        # per-axis matching, X could lock onto one neighbor's corner while Y
        # locks onto a different neighbor's corner, snapping to a point that
        # isn't any real corner at all. Picking the single nearest corner by
        # combined distance and moving both axes together avoids that.
        # Skipped entirely under ortho: it always moves both axes together,
        # which would drag the locked one off its constrained value.
        if x_free and y_free:
            best_combined = tolerance

            for sp in sibling_points:
                dx, dy = sp.x() - anchor.x(), sp.y() - anchor.y()
                combined = max(abs(dx), abs(dy))
                if combined < best_combined:
                    best_combined = combined
                    best_dx, best_dy = dx, dy
                    x_highlight = y_highlight = ("point", sp)

            # Pass 1b: only tried if pass 1 found NO coherent point match at
            # all - point-to-point always outranks point-to-edge, including
            # this rotated-edge variant, the same way Pass 3 (below) is now
            # deprioritized behind Pass 2's point matching. Edges are
            # normally only matched if they're world-horizontal/vertical
            # (_classify_hv_edge), which a rotated belt's edges never are -
            # so two belts built at the same non-axis-aligned angle (e.g. a
            # 30-degree conveyor chain) would otherwise never get edge-to-
            # edge alignment at all, unlike two axis-aligned belts.
            # Re-checking sibling edges in a frame rotated to match THIS
            # item's own rotation catches that case too, but only as a
            # fallback when no keypoint was close enough.
            item_angle = self.rotation() % 90.0
            if x_highlight is None and abs(item_angle) > 1e-6:
                anchor_r = _rotate_vec(anchor, -self.rotation())
                for p1, p2 in sibling_edges:
                    q1, q2 = _rotate_vec(p1, -self.rotation()), _rotate_vec(p2, -self.rotation())
                    classified = _classify_hv_edge(q1, q2)
                    if classified is None:
                        continue
                    kind, value, lo, hi = classified
                    if kind == "v":
                        d = value - anchor_r.x()
                        p1_r, p2_r = QPointF(value, lo), QPointF(value, hi)
                    else:
                        d = value - anchor_r.y()
                        p1_r, p2_r = QPointF(lo, value), QPointF(hi, value)
                    if abs(d) < best_combined:
                        best_combined = abs(d)
                        delta_local = QPointF(d, 0) if kind == "v" else QPointF(0, d)
                        world_delta = _rotate_vec(delta_local, self.rotation())
                        best_dx, best_dy = world_delta.x(), world_delta.y()
                        x_highlight = y_highlight = (
                            "edge", _rotate_vec(p1_r, self.rotation()), _rotate_vec(p2_r, self.rotation())
                        )

            if x_highlight is not None:
                best_dx_dist, best_dy_dist = abs(best_dx), abs(best_dy)

        # Pass 2: edges only get a look-in on an axis where the coherent
        # pass above found nothing at all for it - not merely "closer than
        # the point match", which is what let point-to-edge outrank
        # point-to-point before. Still what provides point-to-edge/
        # edge-to-edge, just deprioritized behind any coherent point match.
        if x_highlight is None or y_highlight is None:
            for p1, p2 in sibling_edges:
                classified = _classify_hv_edge(p1, p2)
                if classified is None:
                    continue
                kind, value, lo, hi = classified
                if kind == "v" and x_free and x_highlight is None:
                    dx = value - anchor.x()
                    if abs(dx) < best_dx_dist:
                        best_dx_dist, best_dx = abs(dx), dx
                        x_highlight = ("edge", QPointF(value, lo), QPointF(value, hi))
                elif kind == "h" and y_free and y_highlight is None:
                    dy = value - anchor.y()
                    if abs(dy) < best_dy_dist:
                        best_dy_dist, best_dy = abs(dy), dy
                        y_highlight = ("edge", QPointF(lo, value), QPointF(hi, value))

        # Pass 3: grid-snap fallback. Deliberately tried BEFORE pass 4's
        # loose independent single-axis point matching, not after (where it
        # used to sit) - in a densely populated layout, almost any anchor
        # position has SOME unrelated, possibly-irrelevant sibling point
        # that happens to share a similar X or Y by pure coincidence, and
        # that used to win over the grid every time it occurred. Since nudge
        # amounts differ per axis in a real layout (this was reported as
        # "grid snap only works for the vertical line, not horizontal" -
        # confirmed via tracing: X kept landing on a real grid line while Y
        # kept getting captured by some distant point that merely happened
        # to share a close Y), that made grid-snap read as broken on
        # whichever axis had more coincidental near-matches, when nothing
        # was actually asymmetric in the code - pass 4 just won too often.
        # Trying the tidy, predictable grid position first fixes that for
        # both axes alike, while a genuine coherent point or a real edge
        # (passes 1-2, above) still correctly outrank the grid.
        if x_highlight is None and x_free:
            grid_x = round(anchor.x() / GRID_SIZE) * GRID_SIZE
            dx = grid_x - anchor.x()
            if abs(dx) < tolerance:
                best_dx, x_highlight = dx, ("grid", grid_x)
        if y_highlight is None and y_free:
            grid_y = round(anchor.y() / GRID_SIZE) * GRID_SIZE
            dy = grid_y - anchor.y()
            if abs(dy) < tolerance:
                best_dy, y_highlight = dy, ("grid", grid_y)

        # Pass 4: last resort - independent per-axis point matching, only
        # for an axis where NEITHER a coherent point, an edge, NOR the grid
        # found anything. Preserves long-range single-axis guide alignment
        # (e.g. sharing a Y with something far away in X) for the
        # increasingly rare case nothing else nearby applies at all.
        if x_highlight is None and x_free:
            for sp in sibling_points:
                dx = sp.x() - anchor.x()
                if abs(dx) < best_dx_dist:
                    best_dx_dist, best_dx, x_highlight = abs(dx), dx, ("point", sp)
        if y_highlight is None and y_free:
            for sp in sibling_points:
                dy = sp.y() - anchor.y()
                if abs(dy) < best_dy_dist:
                    best_dy_dist, best_dy, y_highlight = abs(dy), dy, ("point", sp)

        snapped = candidate_pos + QPointF(best_dx, best_dy)
        anchor_after = anchor + QPointF(best_dx, best_dy)
        v_guides = [anchor_after.x()] if x_highlight is not None else []
        h_guides = [anchor_after.y()] if y_highlight is not None else []
        return snapped, v_guides, h_guides, anchor_after, x_highlight, y_highlight

    def _apply_ortho_constraint(self, candidate_pos: QPointF) -> QPointF:
        """Ortho mode: holding Shift while dragging locks movement to
        horizontal or vertical relative to where the drag started, matching
        AutoCAD/most CAD tools' Shift-constrain convention. Whichever axis
        has moved further from the start wins - the other axis snaps back
        to its starting value and STAYS locked: `_snap` (called right after
        this) is told which axis is locked via `self._ortho_locked_axis` and
        won't let object/grid snapping move it, even if a coherent point
        match is found on both axes. Only the free axis can still be
        fine-tuned by snapping - otherwise a nearby unrelated component
        could silently pull the "locked" axis off its constrained value,
        defeating the point of holding Shift at all.

        Which axis is free is decided ONCE per continuous Shift-hold (the
        first move event after Shift goes down) and then latched for the
        rest of it - re-deciding "whichever axis has moved further" on
        EVERY move event (the original implementation) flip-flops back and
        forth whenever dx and dy happen to be close in magnitude, e.g. from
        ordinary mouse-hand wobble along a mostly-diagonal path. Each flip
        swaps which coordinate is held at `start`, which can be a large
        jump from wherever the other axis had wandered to under the
        previous lock - that's the "random jump" this fixes."""
        if self._drag_start_item_pos is None or not self._drag_shift_held:
            self._ortho_locked_axis = None
            self._ortho_free_axis = None
            return candidate_pos
        start = self._drag_start_item_pos
        if self._ortho_free_axis is None:
            dx = candidate_pos.x() - start.x()
            dy = candidate_pos.y() - start.y()
            if abs(dx) < 1e-9 and abs(dy) < 1e-9:
                # No discernible direction yet (the very first move event
                # can land exactly on the press point) - don't lock an axis
                # off essentially zero displacement, wait for real movement.
                self._ortho_locked_axis = None
                return candidate_pos
            self._ortho_free_axis = "x" if abs(dx) >= abs(dy) else "y"
        if self._ortho_free_axis == "x":
            self._ortho_locked_axis = "y"
            return QPointF(candidate_pos.x(), start.y())
        self._ortho_locked_axis = "x"
        return QPointF(start.x(), candidate_pos.y())

    def itemChange(self, change, value):
        if change == QGraphicsItem.ItemPositionChange and self.scene() and self._dragging:
            value = self._apply_ortho_constraint(value)
            # Cached once at mousePressEvent (see there) rather than
            # rescanning the whole scene on every mouse-move pixel of the
            # drag - the biggest single cost in the alignment system on a
            # canvas with many components.
            sibling_points = self._cached_sibling_points
            sibling_edges = self._cached_sibling_edges
            if sibling_points is None or sibling_edges is None:
                # Defensive fallback (e.g. itemChange firing before
                # mousePressEvent populated the cache, which shouldn't
                # happen in practice but would silently break alignment
                # rather than crash if it ever did).
                sibling_points = self._sibling_key_points()
                sibling_edges = self._sibling_edges()
            snapped, v_guides, h_guides, anchor, x_highlight, y_highlight = self._snap(
                value, sibling_points, sibling_edges, locked_axis=self._ortho_locked_axis
            )
            self.scene().show_guides(v_guides, h_guides, anchor, x_highlight, y_highlight)
            self._pending_group_correction = snapped - value
            return snapped
        return super().itemChange(change, value)

    def mousePressEvent(self, event):
        if _SIM_STATE["playing"]:
            # Simulation mode: canvas select/move/edit is disabled for
            # every component - only ButtonItem's own mousePressEvent
            # (which never reaches this base implementation while playing -
            # see its own "playing" branch) processes a genuine interactive
            # event during a run. `_dragging` deliberately stays False here,
            # which also gates mouseMoveEvent/mouseReleaseEvent below from
            # doing anything for this press.
            event.accept()
            return
        self._dragging = True
        self._drag_mouse_scene_pos = event.scenePos()
        self._drag_start_item_pos = self.pos()
        self._drag_shift_held = bool(event.modifiers() & Qt.ShiftModifier)
        self._ortho_free_axis = None  # fresh drag - decide the free axis anew
        self._pending_group_correction = None
        # Compute the sibling alignment-candidate cache once, up front, for
        # the whole drag (see the cache fields' docstring in __init__) -
        # must happen before super().mousePressEvent() below, which is what
        # actually starts the drag and can trigger itemChange().
        self._cached_sibling_points = self._sibling_key_points()
        self._cached_sibling_edges = self._sibling_edges()
        # Snapshot every OTHER selected item's starting position too - only
        # the item actually clicked gets mousePress/Move/Release at all, so
        # this is the only chance to record where the rest of a
        # multi-selection started (needed for both the undo command and
        # deciding whether each one actually moved).
        if self.scene():
            for other in self.scene().selectedItems():
                if other is not self and isinstance(other, PlacedItem):
                    other._drag_start_item_pos = other.pos()
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        if not self._dragging:
            # No drag was actually started for this item - either
            # simulation mode blocked mousePressEvent above, or (ButtonItem
            # specifically) the press was handled as a momentary interactive
            # "hold to activate" gesture rather than a drag. Without this
            # guard, calling the inherited QGraphicsItem default move
            # behavior here would select/drag the item anyway (confirmed:
            # this is exactly how holding and wiggling the mouse on a
            # button mid-simulation used to select and even reposition it,
            # despite mousePressEvent already having "handled" the press -
            # ButtonItem only overrides mousePressEvent/mouseReleaseEvent,
            # not this method, so it fell through to here unguarded).
            event.accept()
            return
        self._drag_mouse_scene_pos = event.scenePos()
        # Read Shift from this specific event rather than the global
        # QApplication.keyboardModifiers() - the per-event modifiers are
        # what's actually current at the moment Qt computes the new
        # candidate position from this same event, one line down.
        shift_now = bool(event.modifiers() & Qt.ShiftModifier)
        if self._drag_shift_held and not shift_now:
            # Shift released mid-drag - drop the latched axis so pressing
            # Shift again later in the same drag picks a fresh direction
            # instead of resuming the old (possibly now-irrelevant) one.
            self._ortho_free_axis = None
        self._drag_shift_held = shift_now
        self._pending_group_correction = None
        # Qt's default QGraphicsItem drag behavior (triggered inside this
        # super() call) moves every OTHER selected+movable item by the same
        # RAW mouse delta as this one - but only THIS item (the one the
        # cursor actually grabbed) has `_dragging=True` and runs itemChange/
        # _snap, so only it gets alignment/grid/ortho corrections applied.
        # Left alone, the rest of a multi-selection would end up at the
        # raw, unsnapped position while this one snaps - tearing the
        # group's relative layout apart. Nudging every other selected item
        # by the same correction itemChange just computed (available now
        # that super() has already moved them) keeps the whole group rigid
        # and gets the group as a whole the same alignment a single item
        # would have gotten.
        super().mouseMoveEvent(event)
        correction = self._pending_group_correction
        if correction and self.scene() and (abs(correction.x()) > 1e-9 or abs(correction.y()) > 1e-9):
            for other in self.scene().selectedItems():
                if other is not self and isinstance(other, PlacedItem):
                    other.setPos(other.pos() + correction)

    def mouseReleaseEvent(self, event):
        if not self._dragging:
            event.accept()
            return
        super().mouseReleaseEvent(event)
        self._dragging = False
        self._drag_mouse_scene_pos = None
        self._ortho_locked_axis = None
        self._ortho_free_axis = None
        self._cached_sibling_points = None
        self._cached_sibling_edges = None
        if self.scene():
            self.scene().clear_guides()

        moved = []  # (item, start_pos) for everything that actually moved

        def _collect(item):
            start = item._drag_start_item_pos
            item._drag_start_item_pos = None
            if start is not None and (item.pos() - start).manhattanLength() > 1e-6:
                moved.append((item, start))

        _collect(self)
        if self.scene():
            for other in self.scene().selectedItems():
                if other is not self and isinstance(other, PlacedItem):
                    _collect(other)

        if not moved:
            self.model.x, self.model.y = from_scene_pos(self.pos())
            return

        # The drag just landed one or more items at a NEW final position -
        # invalidate the view's cached keypoint/edge list (see
        # CanvasView.invalidate_points_edges_cache()) once here, at the
        # drag's end, rather than on every intermediate mouse-move pixel of
        # the drag itself.
        for view in self.scene().views():
            if hasattr(view, "invalidate_points_edges_cache"):
                view.invalidate_points_edges_cache()

        undo_stack = self.scene().undo_stack if self.scene() else None
        if undo_stack is not None:
            # One combined undo step for the whole group, not one per item -
            # mirrors how a multi-select Delete/Paste already undoes as a
            # single action.
            hook = getattr(self.scene(), "on_items_moved", None)
            multi = len(moved) > 1 or hook is not None
            if multi:
                undo_stack.beginMacro(f"Move {len(moved)} Component{'s' if len(moved) > 1 else ''}")
            for item, start_pos in moved:
                # MoveItemCommand.redo() applies setPos()+model sync itself -
                # each item is already at its final pos() (that's the "new"
                # position being recorded), so pushing just replays the same
                # state, not a second move.
                undo_stack.push(MoveItemCommand(item, start_pos, item.pos()))
            if hook is not None:
                # Same undo step: e.g. connected belts following the drag.
                hook([item for item, _ in moved])
            if multi:
                undo_stack.endMacro()
        else:
            for item, _ in moved:
                item.model.x, item.model.y = from_scene_pos(item.pos())


class BeltItem(PlacedItem):
    """A linear belt: a rectangle by default, an arbitrary polygon when
    `model.shape == "quadrilateral"` and `model.vertexs` is set (freehand,
    triangle, or quadrilateral shapes from the Shape Designer all use this
    same field, any vertex count works), or a true arc when
    `model.type == "curved"` (radius/startAngle/endAngle/beltWidth - the
    same fields physics.py and visualizer.py use for real curved-belt
    kinematics/rendering, not a polygon pretending to be an arc)."""

    kind = "belt"

    def __init__(self, model: Belt):
        super().__init__(model, self._local_points_for_model(model))
        self._sync_brush()

    @staticmethod
    def _local_points_for_model(model: Belt) -> list[QPointF]:
        if model.type == "path":
            outline = _path_footprint_local(model)
            if outline.is_empty:
                return [QPointF(0, 0)] * 3
            return [QPointF(x * SCALE, -y * SCALE) for x, y in list(outline.exterior.coords)[:-1]]
        if model.type == "curved":
            return [
                QPointF(x * SCALE, -y * SCALE)
                for x, y in arc_ring_points(model.radius, model.startAngle, model.endAngle, model.beltWidth)
            ]
        if getattr(model, "shape", "rectangle") == "quadrilateral" and model.vertexs:
            return [QPointF(p["x"] * SCALE, -p["y"] * SCALE) for p in model.vertexs]
        hw, hh = model.length * SCALE / 2.0, model.beltWidth * SCALE / 2.0
        return [QPointF(-hw, -hh), QPointF(hw, -hh), QPointF(hw, hh), QPointF(-hw, hh)]

    def is_custom_shape(self) -> bool:
        return getattr(self.model, "shape", "rectangle") == "quadrilateral" and self.model.type != "curved"

    def is_curved(self) -> bool:
        return self.model.type == "curved"

    def is_path(self) -> bool:
        return self.model.type == "path"

    def _path_painter_path(self) -> QPainterPath:
        """Footprint with any hole (a loop's inside), for paint and hit tests."""
        cached = getattr(self, "_painter_path_cache", None)
        key = _path_signature(self.model)
        if cached is not None and cached[0] == key:
            return cached[1]
        painter_path = QPainterPath()
        painter_path.setFillRule(Qt.OddEvenFill)
        outline = _path_footprint_local(self.model)
        rings = [] if outline.is_empty else [outline.exterior, *outline.interiors]
        for ring in rings:
            painter_path.addPolygon(QPolygonF([QPointF(x * SCALE, -y * SCALE) for x, y in ring.coords]))
            painter_path.closeSubpath()
        self._painter_path_cache = (key, painter_path)
        return painter_path

    def shape(self) -> QPainterPath:
        if self.is_path():
            return self._path_painter_path()
        return super().shape()

    def path_anchor_scene_points(self) -> list[QPointF]:
        """Anchors in this item's local (scene-unit) coordinates."""
        return [QPointF(n.x * SCALE, -n.y * SCALE) for n in (self.model.path or [])]

    def _local_key_points(self):
        if self.is_path():
            return self.path_anchor_scene_points()
        if self.is_curved():
            # A full ring-segment polygon has dozens of vertices (one per
            # rendering segment) - meaningless as individual snap targets.
            # Use the 4 logical corners (inner/outer x start/end) + center
            # instead, the arc equivalent of a rectangle's corners.
            r, s, e, t = self.model.radius, self.model.startAngle, self.model.endAngle, self.model.beltWidth
            inner_r, outer_r = max(0.0, r - t / 2.0), r + t / 2.0
            pts = []
            for angle in (s, e):
                rad = math.radians(angle)
                cos_a, sin_a = math.cos(rad), math.sin(rad)
                for radius in (inner_r, outer_r):
                    pts.append(QPointF(radius * cos_a * SCALE, -radius * sin_a * SCALE))
            pts.append(QPointF(0, 0))
            return pts
        return super()._local_key_points()

    def _local_edges(self):
        if self.is_path():
            nodes = self.model.path or []
            pts = self.path_anchor_scene_points()
            count = len(nodes) if self.model.closed else len(nodes) - 1
            return [(pts[i], pts[(i + 1) % len(nodes)]) for i in range(max(count, 0))
                    if abs(nodes[i].bulge) < 1e-12]
        if self.is_curved():
            # The ring segment's two straight radial edges (inner->outer at
            # the start angle, and again at the end angle) - the arc
            # equivalent of a rectangle's 4 straight edges. The curved outer/
            # inner arc edges themselves aren't included since they're never
            # horizontal/vertical (edge alignment is scoped to H/V only) and
            # their corner points are already covered by `_local_key_points`.
            r, s, e, t = self.model.radius, self.model.startAngle, self.model.endAngle, self.model.beltWidth
            inner_r, outer_r = max(0.0, r - t / 2.0), r + t / 2.0
            edges = []
            for angle in (s, e):
                rad = math.radians(angle)
                cos_a, sin_a = math.cos(rad), math.sin(rad)
                p_inner = QPointF(inner_r * cos_a * SCALE, -inner_r * sin_a * SCALE)
                p_outer = QPointF(outer_r * cos_a * SCALE, -outer_r * sin_a * SCALE)
                edges.append((p_inner, p_outer))
            return edges
        return super()._local_edges()

    def _sync_brush(self):
        self.setBrush(QBrush(QColor(self.model.color)))
        self.setPen(Qt.NoPen)

    def set_size(self, length: float, belt_width: float):
        """Only meaningful for the plain-rectangle shape (custom shapes and
        arcs don't expose Length/Width in the properties panel)."""
        self.model.length = length
        self.model.beltWidth = belt_width
        hw, hh = length * SCALE / 2.0, belt_width * SCALE / 2.0
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF([QPointF(-hw, -hh), QPointF(hw, -hh), QPointF(hw, hh), QPointF(-hw, hh)]))

    def sync_from_model(self):
        """Re-read position, rotation and shape from the model (after the
        CAD tools change a belt's geometry - see layout_editor_cad.py)."""
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF(self._local_points_for_model(self.model)))
        self.setPos(to_scene_pos(self.model.x, self.model.y))
        self.setRotation(-self.model.rotation)
        self.update()

    def set_arc_params(self, radius: float, start_angle: float, end_angle: float, belt_width: float):
        self.model.radius = radius
        self.model.startAngle = start_angle
        self.model.endAngle = end_angle
        self.model.beltWidth = belt_width
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF(self._local_points_for_model(self.model)))

    def _paint_path(self, painter: QPainter, option):
        painter.setPen(Qt.NoPen)
        painter.setBrush(QBrush(QColor(self.model.color)))
        painter.drawPath(self._path_painter_path())
        if option.state & QStyle.State_Selected:
            painter.setPen(QPen(QColor(255, 255, 255), 0, Qt.DashLine))
            painter.setBrush(Qt.NoBrush)
            painter.drawPath(self._path_painter_path())
        # Centerline, and flow arrows spaced along it.
        pts, bulges = belt_local_path(self.model)
        segs = path_segments(pts, bulges, self.model.closed)
        if not segs:
            return
        flat, _ = path_flatten(segs, tolerance=0.01)
        painter.setPen(QPen(QColor(255, 140, 0, 160), 0, Qt.DashLine))
        painter.setBrush(Qt.NoBrush)
        painter.drawPolyline(QPolygonF([QPointF(x * SCALE, -y * SCALE) for x, y in flat]))
        total = path_length(segs)
        step = max(total / 6.0, 1.0)
        backwards = path_flow_sign(self.model) < 0
        painter.setPen(QPen(QColor(255, 140, 0), 2))
        painter.setBrush(QBrush(QColor(255, 140, 0)))
        d = step / 2.0
        while d < total:
            acc = 0.0
            for seg in segs:
                if acc + seg.length >= d:
                    t = (d - acc) / seg.length if seg.length > 0 else 0.0
                    x, y = seg.point_at(t)
                    h = seg.heading_at(t) + (math.pi if backwards else 0.0)
                    c, sn = math.cos(h), math.sin(h)
                    px, py = x * SCALE, -y * SCALE
                    tip = QPointF(px + 8 * c, py - 8 * sn)
                    left = QPointF(px - 6 * c - 5 * sn, py + 6 * sn - 5 * c)
                    right = QPointF(px - 6 * c + 5 * sn, py + 6 * sn + 5 * c)
                    painter.drawPolygon(QPolygonF([tip, left, right]))
                    break
                acc += seg.length
            d += step
        x, y = segs[0].point_at(0.0)
        painter.setPen(QPen(Qt.white))
        painter.drawText(QPointF(x * SCALE + 4, -y * SCALE - 4), f"{self.model.id}  speed={self.model.speed:.2f}")

    def paint(self, painter: QPainter, option, widget=None):
        if self.is_path():
            self._paint_path(painter, option)
            return
        super().paint(painter, option, widget)
        # Direction arrow, rotated locally by `directionAngle` (the belt's
        # travel direction offset from its own shape orientation - see
        # physics.py's `rotation + directionAngle`), plus a speed label.
        rect = self.polygon().boundingRect()
        painter.save()
        painter.translate(rect.center())
        # Qt's local painter.rotate() is clockwise-positive too, so negate
        # to keep directionAngle CCW-positive like the rest of the model.
        painter.rotate(-self.model.directionAngle)
        painter.setPen(QPen(QColor(255, 140, 0), 2))
        arrow_len = max(rect.width(), rect.height()) * 0.35
        painter.drawLine(QPointF(-arrow_len / 2, 0), QPointF(arrow_len / 2, 0))
        head = QPolygonF([
            QPointF(arrow_len / 2, 0),
            QPointF(arrow_len / 2 - 8, -5),
            QPointF(arrow_len / 2 - 8, 5),
        ])
        painter.setBrush(QBrush(QColor(255, 140, 0)))
        painter.drawPolygon(head)
        painter.restore()
        painter.setPen(QPen(Qt.white))
        painter.drawText(rect, Qt.AlignCenter, f"{self.model.id}\nspeed={self.model.speed:.2f}")


class SensorItem(PlacedItem):
    """An IR or laser-banner sensor. `physics.py`'s `evaluate_sensors()`
    writes detection results directly onto `sensor.sensor_states` on the
    same model object this item wraps ("0"/"1" for IR, a per-beam bit
    string for laser banners) - `paint()` reads it live each repaint, and
    `MainWindow._tick()` calls `.update()` on every SensorItem after each
    physics step so the paint actually refreshes. In standalone demo mode
    (no physics engine) `sensor_states` stays None/unset and everything
    just renders in the idle/clear state."""

    kind = "sensor"

    def __init__(self, model: Sensor):
        hw, hh = model.width * SCALE / 2.0, model.height * SCALE / 2.0
        pts = [QPointF(-hw, -hh), QPointF(hw, -hh), QPointF(hw, hh), QPointF(-hw, hh)]
        super().__init__(model, pts)
        self._sync_brush()

    def _sync_brush(self):
        if self.model.sensorType == "laser_banner":
            self.setBrush(QBrush(QColor(255, 50, 50, 100)))
        else:
            color = QColor(self.model.color)
            color.setAlpha(100)
            self.setBrush(QBrush(color))
        self.setPen(Qt.NoPen)

    def set_size(self, width: float, height: float):
        self.model.width = width
        self.model.height = height
        hw, hh = width * SCALE / 2.0, height * SCALE / 2.0
        self.prepareGeometryChange()
        self.setPolygon(QPolygonF([QPointF(-hw, -hh), QPointF(hw, -hh), QPointF(hw, hh), QPointF(-hw, hh)]))

    def paint(self, painter: QPainter, option, widget=None):
        # Recomputed fresh every repaint (not cached) so a trigger from a
        # passing parcel shows up the moment MainWindow._tick() calls
        # update() after a physics step.
        triggered = self.model.sensorType == "ir" and self.model.sensor_states in ("1", 1, True)
        self.setPen(QPen(QColor(255, 0, 0), 3) if triggered else Qt.NoPen)
        super().paint(painter, option, widget)
        rect = self.polygon().boundingRect()
        painter.setPen(QPen(Qt.white))
        painter.drawText(rect, Qt.AlignCenter, f"{self.model.id}\n{self.model.label}")
        if self.model.sensorType == "laser_banner":
            laser_count = self.model.laserCount or 16
            beam_dist = (self.model.beamDistance or 0.05) * SCALE
            total_span = beam_dist * (laser_count - 1)
            state = self.model.sensor_states if isinstance(self.model.sensor_states, str) else None
            painter.setPen(Qt.NoPen)
            for i in range(laser_count):
                # physics.py computes `by = (i - (laser_count-1)/2) * beam_dist`
                # in true world-convention (Y-up) local space - matches `t`
                # below exactly. But this is drawn directly in Qt's local
                # (Y-down) space, so it needs the same negation every other
                # local-geometry conversion in this file applies (e.g. belt
                # vertices); without it, beam index 0 rendered where index
                # laser_count-1 belongs - the whole row was mirrored.
                t = -total_span / 2.0 + i * beam_dist
                blocked = bool(state) and i < len(state) and state[i] == "1"
                painter.setBrush(QBrush(QColor(255, 0, 0) if blocked else QColor(0, 255, 0)))
                painter.drawEllipse(QPointF(0, -t), 2, 2)


