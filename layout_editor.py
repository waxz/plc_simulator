class PropertiesPanel(QWidget):
    """Property grid of the selected component - like an engineering tool's:
    a header naming it, then its fields in collapsible sections (Identity,
    Position, Geometry, Motion, Signal, Operation, Display - the same
    sections, in the same order, as the simulator window's panel), numbers
    with their units. Rebuilt on selection change to match the item's type
    (see `_field_specs_for`); every edit goes through the undo stack."""

    def __init__(self, scene: SnapGuideScene, items, on_model_changed=None):
        super().__init__()
        self.scene = scene
        self.items_list = items
        self.on_model_changed = on_model_changed
        # Set externally by MainWindow once both exist.
        self.undo_stack: Optional[QUndoStack] = None
        # Set by the CAD controller: fills the grid for one selected sketch
        # line/arc/circle, returns False if the selection holds none.
        self.sketch_fields = None
        self.current: Optional[PlacedItem] = None
        self.spins = {}
        self.texts = {}
        self.combos = {}
        self.checkboxes = {}
        self.id_edit: Optional[QLineEdit] = None
        self.color_btn: Optional[QPushButton] = None
        self._collapsed_groups = set()
        self.io_rows = {}                   # PLC I/O (_build_io): signal name -> its row

        outer = QVBoxLayout(self)
        outer.setContentsMargins(4, 4, 4, 4)
        outer.setSpacing(4)
        self.header = QLabel()
        self.header.setTextFormat(Qt.RichText)
        self.header.setWordWrap(True)
        self.header.setContentsMargins(4, 2, 4, 4)
        outer.addWidget(self.header)
        self.tree = QTreeWidget()
        self.tree.setColumnCount(2)
        self.tree.setHeaderLabels(["Property", "Value"])
        self.tree.setIndentation(10)
        self.tree.setSelectionMode(QAbstractItemView.NoSelection)
        self.tree.setFocusPolicy(Qt.NoFocus)
        self.tree.setUniformRowHeights(False)
        self.tree.header().setStretchLastSection(True)
        self.tree.itemCollapsed.connect(lambda it: self._collapsed_groups.add(it.text(0)))
        self.tree.itemExpanded.connect(lambda it: self._collapsed_groups.discard(it.text(0)))
        outer.addWidget(self.tree, 1)
        self.empty = QLabel("Select a component on the canvas\nto see and edit its properties.")
        self.empty.setAlignment(Qt.AlignCenter)
        self.empty.setWordWrap(True)
        outer.addWidget(self.empty, 1)
        self._show_empty()
        scene.selectionChanged.connect(self._on_selection_changed)

    def _show_empty(self):
        self.header.hide()
        self.tree.hide()
        self.empty.show()
        self.setEnabled(False)

    def _on_selection_changed(self):
        try:
            selected = [i for i in self.scene.selectedItems() if isinstance(i, PlacedItem)]
        except RuntimeError:
            return  # the scene is being destroyed (window deleted without closing it first)
        if len(selected) == 1:
            self.current = selected[0]
            self._rebuild_fields()
            self._load()
            self.setEnabled(True)
            self.empty.hide()
            self.header.show()
            self.tree.show()
        else:
            self.current = None
            self._clear_dynamic_rows()
            self._group_items = {}
            if not selected and self.sketch_fields is not None and self.sketch_fields(self):
                self.setEnabled(True)
                self.empty.hide()
                self.header.show()
                self.tree.show()
                return
            self.empty.setText("Select a component on the canvas\nto see and edit its properties."
                               if not selected else f"{len(selected)} components selected.\n"
                               "Select one to edit its properties.")
            self._show_empty()

    def _clear_dynamic_rows(self):
        self.tree.clear()  # deletes the editor widgets too
        self.spins.clear()
        self.texts.clear()
        self.combos.clear()
        self.checkboxes.clear()
        self.id_edit = None
        self.color_btn = None
        self.io_rows = {}
        self.motor_preset = None
        self.drive_summary = None
        self.elements_editor = None

    def _update_header(self):
        item = self.current
        if item is None:
            return
        dim = hmi.hex_(hmi.TEXT_DIM)
        details = ComponentManagerPanel.describe(item)
        self.header.setText(f"<span style='font-size:8pt; color:{dim}; letter-spacing:1px'>{item.kind.upper()}</span>"
                            f"<br><b style='font-size:11pt'>{item.model.id}</b>"
                            f"<br><span style='color:{dim}'>{details}</span>")

    def _add_row(self, group: str, label: str, widget: QWidget, span: bool = False):
        groups = self.__dict__.setdefault("_group_items", {})
        parent = groups.get(group)
        if parent is None:
            parent = QTreeWidgetItem([group])
            font = parent.font(0)
            font.setBold(True)
            parent.setFont(0, font)
            parent.setForeground(0, QBrush(hmi.qcolor(hmi.ACCENT)))
            parent.setFlags(Qt.ItemIsEnabled)
            self.tree.addTopLevelItem(parent)
            parent.setFirstColumnSpanned(True)
            groups[group] = parent
        row = QTreeWidgetItem(["" if span else label])
        row.setFlags(Qt.ItemIsEnabled)
        parent.addChild(row)
        if span:
            row.setFirstColumnSpanned(True)
            self.tree.setItemWidget(row, 0, widget)
        else:
            self.tree.setItemWidget(row, 1, widget)
        return row

    def _rebuild_fields(self):
        self._clear_dynamic_rows()
        self._group_items = {}
        item = self.current
        if not item:
            return
        self.id_edit = QLineEdit()
        self.id_edit.editingFinished.connect(self._apply_id)
        self._add_row("Identity", "Id", self.id_edit)
        specs = sorted(_field_specs_for(item), key=lambda spec: hmi.group_sort_key(spec[1]))
        for spec in specs:
            field_kind, attr, label = spec[0], spec[1], spec[2]
            if field_kind == "float":
                _, _, _, lo, hi, step = spec
                widget = QDoubleSpinBox()
                widget.setRange(lo, hi)
                widget.setDecimals(hmi.PROPERTY_DECIMALS.get(attr, 3))
                widget.setSingleStep(step)
                widget.setSuffix(_FIELD_UNITS.get(attr, ""))
                widget.valueChanged.connect(lambda v, a=attr: self._apply_field(a, v))
                self.spins[attr] = widget
            elif field_kind == "int":
                _, _, _, lo, hi = spec
                widget = QSpinBox()
                widget.setRange(lo, hi)
                widget.valueChanged.connect(lambda v, a=attr: self._apply_field(a, v))
                self.spins[attr] = widget
            elif field_kind == "text":
                widget = QLineEdit()
                widget.editingFinished.connect(lambda a=attr: self._apply_text_field(a))
                self.texts[attr] = widget
            elif field_kind == "combo":
                _, _, _, options = spec
                widget = QComboBox()
                widget.addItems([hmi.combo_label(attr, option) for option in options])
                widget.currentTextChanged.connect(
                    lambda text, a=attr: self._apply_combo_field(a, hmi.combo_value(a, text)))
                self.combos[attr] = widget
            elif field_kind == "motor":
                widget = QComboBox()
                widget.addItems([name for name, _rpm, _hz in drivetrain.MOTOR_PRESETS] + [drivetrain.CUSTOM_MOTOR])
                widget.currentTextChanged.connect(self._apply_motor_preset)
                self.motor_preset = widget
            elif field_kind == "elements":
                widget = PanelElementsEditor(lambda elements: self._apply_elements(elements))
                self.elements_editor = widget
            elif field_kind == "summary":
                widget = QLabel()
                widget.setWordWrap(True)
                widget.setContentsMargins(8, 4, 8, 6)
                widget.setMinimumHeight(widget.fontMetrics().lineSpacing() * 4 + 10)
                self.drive_summary = widget
            elif field_kind == "bool":
                widget = QCheckBox()
                widget.toggled.connect(lambda checked, a=attr: self._apply_bool_field(a, checked))
                self.checkboxes[attr] = widget
            else:
                continue
            widget.setToolTip(attr)
            if field_kind in ("float", "int") and attr[len("drive."):] in _DRIVE_ZERO_IS_NONE:
                widget.setSpecialValueText("not set")      # 0 = None: the drive's accel / surface encoder
            # The result and the element table: the whole width, no label.
            self._add_row(hmi.property_group(attr), label, widget, span=field_kind in ("summary", "elements"))
        if hasattr(item.model, "color"):
            self.color_btn = QPushButton("-")
            self.color_btn.clicked.connect(self._pick_color)
            self._add_row("Display", "Color", self.color_btn)
        self._build_io()
        for group, tree_item in self._group_items.items():
            tree_item.setExpanded(group not in self._collapsed_groups)
        self.tree.resizeColumnToContents(0)
        self._update_header()

    # Some model fields are `Optional[...] = None` (e.g. Sensor.laserCount/
    # beamDistance when a config never set them) - QSpinBox/QDoubleSpinBox
    # both raise TypeError on setValue(None), so fall back to a sensible
    # per-field default at *display* time rather than crashing (mirrors
    # physics.py's own `laser_count_val if ... is not None else 16` pattern
    # - it doesn't silently mutate the model, just treats None as this
    # value for display until the user actually edits it).
    _OPTIONAL_FIELD_DEFAULTS = {"laserCount": 16, "beamDistance": 0.05}

    def _load(self):
        item = self.current
        if not item:
            return
        for widget in (*self.spins.values(), *self.texts.values(), *self.combos.values(), *self.checkboxes.values()):
            widget.blockSignals(True)

        if self.id_edit is not None:
            self.id_edit.blockSignals(True)
            self.id_edit.setText(item.model.id)
            self.id_edit.setStyleSheet("")
            self.id_edit.setToolTip("")
            self.id_edit.blockSignals(False)

        for attr, widget in self.spins.items():
            value = _shown_value(item.model, attr)
            if value is None:
                value = self._OPTIONAL_FIELD_DEFAULTS.get(attr, 0)
            widget.setValue(value)
        for attr, widget in self.texts.items():
            widget.setText(_field_text(attr, getattr(item.model, attr)))
        for attr, widget in self.combos.items():
            widget.setCurrentText(hmi.combo_label(attr, getattr(item.model, attr)))
        for attr, widget in self.checkboxes.items():
            widget.setChecked(bool(getattr(item.model, attr)))

        for widget in (*self.spins.values(), *self.texts.values(), *self.combos.values(), *self.checkboxes.values()):
            widget.blockSignals(False)
        self._update_color_swatch()
        self._refresh_drive_rows()
        if getattr(self, "elements_editor", None) is not None:
            self.elements_editor.set_elements(item.model.elements)

    def _apply_elements(self, elements):
        """The panel's new element list (the table's edit), one undo step."""
        item = self.current
        if item is None:
            return
        old = [e.model_copy() for e in item.model.elements]
        self._push_property_change(item, "elements", old, [e.model_copy() for e in elements],
                                   self._do_apply_elements, text="Edit Panel Elements")

    def _do_apply_elements(self, item, attr: str, value):
        item.model.elements = [e.model_copy() for e in value]
        item.update()
        if item is self.current and getattr(self, "elements_editor", None) is not None:
            self.elements_editor.set_elements(item.model.elements)
            self._rebuild_io_later()
        if self.on_model_changed:
            self.on_model_changed()

    def _rebuild_io_later(self):
        # The element list changed: so did the PLC I/O rows (next tick, not
        # inside the table's own signal).
        QTimer.singleShot(0, self._rebuild_and_reload)

    def _refresh_drive_rows(self):
        """The motor preset matching the nameplate, and the drive train's
        result in words (with a warning when the design speed is out of
        reach) - after any edit, since speed and every train value count."""
        item = self.current
        preset = getattr(self, "motor_preset", None)
        summary = getattr(self, "drive_summary", None)
        if item is None or not isinstance(item.model, (Belt, Elevator, Turntable, Transfer)):
            return
        if preset is not None:
            preset.blockSignals(True)
            preset.setCurrentText(drivetrain.motor_preset(_shown_value(item.model, "drive.motorRatedSpeed"),
                                                          _shown_value(item.model, "drive.motorRatedFrequency")))
            preset.blockSignals(False)
        if summary is not None:
            text, warning = drivetrain.summary(item.model)
            colour = hmi.hex_(hmi.ALARM) if warning else hmi.hex_(hmi.TEXT_DIM)
            summary.setText(warning or text)
            summary.setStyleSheet(f"color: {colour}")
            summary.setToolTip(text)

    def _apply_motor_preset(self, name: str):
        """A nameplate from the list: rated speed and frequency, one undo step."""
        match = next(((rpm, hz) for preset, rpm, hz in drivetrain.MOTOR_PRESETS if preset == name), None)
        if match is None or self.current is None:
            return
        if self.undo_stack is not None:
            self.undo_stack.beginMacro(f"Motor {name}")
        self._apply_field("drive.motorRatedSpeed", match[0])
        self._apply_field("drive.motorRatedFrequency", match[1])
        if self.undo_stack is not None:
            self.undo_stack.endMacro()

    def _push_property_change(self, item, attr: str, old_value, new_value, do_apply, text=None):
        """Route a property edit through the undo stack (if attached),
        otherwise apply it directly. `do_apply(item, attr, value)` performs
        the actual model mutation + visual refresh for this specific field -
        shared between the live edit and undo/redo replay."""
        apply_fn = lambda it, v, a=attr: do_apply(it, a, v)
        if self.undo_stack is not None:
            self.undo_stack.push(PropertyEditCommand(item, apply_fn, old_value, new_value, text or f"Edit {attr}"))
        else:
            apply_fn(item, new_value)

    def _resync_widget(self, item, attr: str):
        """After undo/redo replays a value (or any programmatic apply),
        refresh the ON-SCREEN widget for that field too, if the affected
        item is still selected - otherwise the panel would show a stale
        value until the next selection change."""
        if item is not self.current:
            return
        value = _shown_value(item.model, attr) if attr.startswith("drive.") else getattr(item.model, attr, None)
        for widgets, setter in (
            (self.spins, lambda w, v: w.setValue(v if v is not None else self._OPTIONAL_FIELD_DEFAULTS.get(attr, 0))),
            (self.texts, lambda w, v: w.setText(_field_text(attr, v))),
            (self.combos, lambda w, v: w.setCurrentText(hmi.combo_label(attr, v))),
            (self.checkboxes, lambda w, v: w.setChecked(bool(v))),
        ):
            widget = widgets.get(attr)
            if widget is not None:
                widget.blockSignals(True)
                setter(widget, value)
                widget.blockSignals(False)
                return

    def _apply_field(self, attr: str, value):
        item = self.current
        if not item:
            return
        old_value = _model_value(item.model, attr)
        if old_value == value:
            return
        self._push_property_change(item, attr, old_value, value, self._do_apply_field)

    def _do_apply_field(self, item, attr: str, value):
        if item is self.current:
            QTimer.singleShot(0, self._update_header)
        """Apply a single edited field, touching only the Qt geometry that
        field actually affects - not all of setPos/setRotation/set_size on
        every keystroke, which used to re-trigger the drag-snap logic (and
        its guide-line overlay) even for unrelated edits like `speed`."""
        _set_model_value(item.model, attr, value)
        if attr in ("x", "y"):
            item.setPos(to_scene_pos(item.model.x, item.model.y))
        elif attr == "rotation":
            item.setRotation(-value)
        elif isinstance(item, BeltItem) and item.is_curved() and attr in ("radius", "startAngle", "endAngle", "beltWidth"):
            item.set_arc_params(item.model.radius, item.model.startAngle, item.model.endAngle, item.model.beltWidth)
        elif isinstance(item, BeltItem) and item.is_path() and attr in ("beltWidth", "cornerRadius"):
            item.sync_from_model()
        elif isinstance(item, BeltItem) and not item.is_curved() and attr in ("length", "beltWidth"):
            item.set_size(item.model.length, item.model.beltWidth)
        elif attr in ("width", "height") and isinstance(item, (SensorItem, SinkItem, ButtonItem, ControlPanelItem)):
            item.set_size(item.model.width, item.model.height)
        elif attr in ("maxWidth", "maxHeight") and isinstance(item, SourceItem):
            item.set_size(item.model.maxWidth, item.model.maxHeight)
        elif attr == "radius" and isinstance(item, LedItem):
            item.set_size(item.model.radius)
        elif hasattr(item, "refresh_shape"):
            item.refresh_shape()
        item.update()
        # This is the only field-edit path that can move/resize an item's
        # keypoints (position, rotation, length, size, arc params) - the
        # view's cached keypoint/edge list (CanvasView._all_points_and_edges)
        # would otherwise keep offering this item's PRE-edit geometry as a
        # hover/measure snap target for the rest of the session.
        if self.scene:
            for view in self.scene.views():
                if hasattr(view, "invalidate_points_edges_cache"):
                    view.invalidate_points_edges_cache()
        self._resync_widget(item, attr)
        if item is self.current:
            self._refresh_drive_rows()

    def _apply_text_field(self, attr: str):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        new_value = self.texts[attr].text()
        if attr in _LIST_FIELDS:
            new_value = _parse_list(attr, new_value)
            if new_value is None:                    # not a list of that type: show the old one again
                self.texts[attr].setText(_field_text(attr, old_value))
                return
        elif attr in ("beltId", "resetButtonId", "pickSensorId"):
            new_value = new_value.strip() or None
        if attr == "key":
            new_value = new_value.strip()[:1].lower() or None  # one key, or none
        if old_value == new_value:
            return
        self._push_property_change(item, attr, old_value, new_value, self._do_apply_text_field)

    def _do_apply_text_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        item.update()
        self._resync_widget(item, attr)

    def _apply_bool_field(self, attr: str, checked: bool):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        if bool(old_value) == checked:
            return
        self._push_property_change(item, attr, old_value, checked, self._do_apply_bool_field)

    def _do_apply_bool_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        item.update()
        self._resync_widget(item, attr)

    def _apply_combo_field(self, attr: str, text: str):
        item = self.current
        if not item:
            return
        old_value = getattr(item.model, attr)
        if old_value == text:
            return
        self._push_property_change(item, attr, old_value, text, self._do_apply_combo_field)

    def _do_apply_combo_field(self, item, attr: str, value):
        setattr(item.model, attr, value)
        if attr == "sensorType" and value == "laser_banner":
            item.model.laserCount = item.model.laserCount or 16
            item.model.beamDistance = item.model.beamDistance or 0.05
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        if isinstance(item, _MachineItem):
            item.refresh_shape()                # e.g. a diverter's type changes what it draws
        item.update()
        if item is self.current:
            if attr in ("sensorType", "surface", "commandFormat"):
                # Adding/removing laserCount/beamDistance rows here (mid-
                # signal, inside this very combo box's own currentTextChanged
                # handler) would delete a widget while it's still emitting -
                # defer one tick so Qt finishes the current event first.
                QTimer.singleShot(0, self._rebuild_and_reload)
            else:
                self._resync_widget(item, attr)

    def _rebuild_and_reload(self):
        if not self.current:
            return
        self._rebuild_fields()
        self._load()

    # -- PLC I/O --------------------------------------------------------------------

    def _build_io(self):
        """The PLC I/O sections: where the commands come from (`control`, a
        layout setting) and every PLC signal - its commands and its
        feedback, named and typed as on the wire (io_signals.py). The live
        values, and setting the commands by hand in "manual", are in the
        simulator window's inspector."""
        model = self.current.model
        if isinstance(model, ControlPanel):
            # Its elements are the buttons / lamps on the wire: one signal each, by component id.
            buttons, lamps = control_panel.children(model)
            signals = [dataclass_replace(s, name=child.id) for child in (*buttons, *lamps) for s in io_signals.signals(child)]
        else:
            signals = io_signals.signals(model)
        if not signals:
            return
        options = io_signals.control_options(model)
        if options:
            combo = QComboBox()
            combo.addItems(options)
            combo.setToolTip(_CONTROL_TIP)
            combo.currentTextChanged.connect(lambda text: self._apply_combo_field("control", text))
            self.combos["control"] = combo
            self._add_row(IO_GROUP, "Command source", combo)
        dim = hmi.hex_(hmi.TEXT_DIM)
        for signal in signals:
            plc_type = QLabel(signal.plc_type)
            plc_type.setStyleSheet(f"color: {dim}")
            command = signal.direction == "command"
            row = self._add_row(IO_COMMANDS if command else IO_FEEDBACK, signal.name, plc_type)
            row.setToolTip(0, f"{model.id}/{signal.name}: {signal.plc_type}, "
                              f"{'PLC -> simulator' if command else 'simulator -> PLC'}")
            self.io_rows[signal.name] = row

    def _apply_id(self):
        item = self.current
        if not item:
            return
        new_id = self.id_edit.text().strip()
        other_ids = {i.model.id for i in self.items_list if i is not item}
        if not new_id or new_id in other_ids:
            self.id_edit.setStyleSheet("border: 1px solid #ff5555;")
            self.id_edit.setToolTip("Id must be non-empty and unique - reverted")
            self.id_edit.setText(item.model.id)
            return
        self.id_edit.setStyleSheet("")
        self.id_edit.setToolTip("")
        old_id = item.model.id
        if old_id == new_id:
            return
        self._push_property_change(item, "id", old_id, new_id, self._do_apply_id, text="Edit Id")

    def _do_apply_id(self, item, attr: str, value):
        item.model.id = value
        item.update()
        if self.on_model_changed:
            self.on_model_changed()
        if item is self.current:
            self._update_header()
            self.id_edit.blockSignals(True)
            self.id_edit.setText(value)
            self.id_edit.blockSignals(False)

    def _pick_color(self):
        # Source/Sink have no `.color` field at all - visualizer.py draws
        # them with fixed colors too, so there's nothing to persist a pick
        # to. _update_color_swatch disables the button for these kinds.
        if not self.current or not hasattr(self.current.model, "color"):
            return
        item = self.current
        chosen = QColorDialog.getColor(QColor(item.model.color), self, "Color")
        if not chosen.isValid():
            return
        old_color, new_color = item.model.color, chosen.name()
        if old_color == new_color:
            return
        self._push_property_change(item, "color", old_color, new_color, self._do_apply_color, text="Edit Color")

    def _do_apply_color(self, item, attr: str, value):
        item.model.color = value
        if hasattr(item, "_sync_brush"):
            item._sync_brush()
        if item is self.current:
            self._update_color_swatch()

    def _update_color_swatch(self):
        if self.color_btn is None:
            return
        if self.current and hasattr(self.current.model, "color"):
            self.color_btn.setEnabled(True)
            self.color_btn.setStyleSheet(f"background-color: {self.current.model.color};")
            self.color_btn.setText(self.current.model.color)
        elif self.current:
            self.color_btn.setEnabled(False)
            self.color_btn.setStyleSheet("")
            self.color_btn.setText("N/A")
        else:
            self.color_btn.setEnabled(False)
            self.color_btn.setStyleSheet("")
            self.color_btn.setText("-")


