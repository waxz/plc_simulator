"""test_pack_format_auto_generation.py - a component's packFormat (config_
parser.py: Sensor/ControlButton/LedIndicator, defaulting to "bit") decides
how paddng_component()/custom_component_mapping() lay it out on the wire -
"bit" (indexed BIT entries, auto-padded) or a compact BYTE/UINT16/UINT32/
FLOAT register - entirely from what's declared in config. No caller (CLI,
web UI, or these tests) hand-picks a ByteType or inserts padding; that's
the whole point of this feature.
"""
import unittest

from config_parser import Belt, ControlButton, LedIndicator, Sensor, load_config
from mqtt_message_binding import ByteType, ComponentMessage, custom_component_mapping, paddng_component, verify_component_list


class _StubConfig:
    """Bypasses SimulatorConfig's belts/sources/sinks requirements so tests
    can declare just the sensors/buttons/leds they need."""
    def __init__(self, sensors=None, buttons=None, leds=None, belts=None):
        self.sensors = sensors or []
        self.buttons = buttons or []
        self.leds = leds or []
        self.belts = belts or []


def _ir_sensor(id_, pack_format="bit"):
    return Sensor(id=id_, x=0, y=0, width=0.1, height=1, rotation=0, label="s", color="#f00",
                  sensorType="ir", sensor_states="0", packFormat=pack_format)


def _laser_banner(id_, laser_count=32, pack_format="bit"):
    return Sensor(id=id_, x=0, y=0, width=0.1, height=1, rotation=0, label="lb", color="#f00",
                  sensorType="laser_banner", laserCount=laser_count, sensor_states="0" * laser_count,
                  packFormat=pack_format)


def _button(id_, pack_format="bit"):
    return ControlButton(id=id_, x=0, y=0, label="b", sensor_states=False, packFormat=pack_format)


def _led(id_, pack_format="bit"):
    return LedIndicator(id=id_, x=0, y=0, label="l", isOn=False, packFormat=pack_format)


class PackFormatDefaultsToBitTest(unittest.TestCase):
    def test_config_models_default_packformat_to_bit(self):
        self.assertEqual(_ir_sensor("s").packFormat, "bit")
        self.assertEqual(_button("b").packFormat, "bit")
        self.assertEqual(_led("l").packFormat, "bit")

    def test_a_config_with_no_packformat_field_at_all_still_loads(self):
        # test_fixture_config.json predates this field for every component except
        # sensor_1 - proves the field is additive, not a breaking schema
        # change, for every other component in a real config file.
        config = load_config("test_fixture_config.json")
        untouched = next(s for s in config.sensors if s.id != "sensor_1")
        self.assertEqual(untouched.packFormat, "bit")


class AutoGeneratedCompactFieldTest(unittest.TestCase):
    def test_a_compact_sensor_produces_one_row_no_manual_authoring(self):
        config = _StubConfig(sensors=[_laser_banner("banner", pack_format="uint32")])
        mapping = paddng_component(config, sensor_id=["banner"])
        self.assertEqual(mapping, [(ByteType.UINT32, "banner/sensor_states")])

    def test_a_compact_button_and_led_each_produce_one_row(self):
        config = _StubConfig(buttons=[_button("btn", "byte")], leds=[_led("lamp", "uint16")])
        mapping = paddng_component(config, sensor_id=["btn", "lamp"])
        self.assertEqual(mapping, [
            (ByteType.BYTE, "btn/sensor_states"),
            (ByteType.UINT16, "lamp/isOn"),
        ])

    def test_bit_items_before_a_compact_field_are_auto_padded_to_a_byte(self):
        """The exact scenario the padding used to require a human to
        count: two BIT items (2 bits pending) followed by a compact field -
        6 padding bits must appear automatically before it."""
        config = _StubConfig(
            buttons=[_button("b1"), _button("b2")],
            sensors=[_laser_banner("banner", pack_format="uint32")],
        )
        mapping = paddng_component(config, sensor_id=["b1", "b2", "banner"])
        self.assertEqual(mapping[:2], [
            (ByteType.BIT, "b1/sensor_states[0]"),
            (ByteType.BIT, "b2/sensor_states[0]"),
        ])
        padding = mapping[2:8]
        self.assertEqual(len(padding), 6)
        self.assertTrue(all(bt == ByteType.BIT and path.startswith("padding_") for bt, path in padding))
        self.assertEqual(mapping[8], (ByteType.UINT32, "banner/sensor_states"))

    def test_bit_items_are_not_padded_when_already_byte_aligned(self):
        config = _StubConfig(
            buttons=[_button(f"b{i}") for i in range(8)],
            sensors=[_laser_banner("banner", pack_format="uint32")],
        )
        mapping = paddng_component(config, sensor_id=[f"b{i}" for i in range(8)] + ["banner"])
        self.assertEqual(len(mapping), 9)  # 8 bits, no padding, then the compact field
        self.assertEqual(mapping[-1], (ByteType.UINT32, "banner/sensor_states"))

    def test_a_bit_format_laser_banner_still_defers_to_the_end_unchanged(self):
        """Regression: a packFormat="bit" laser banner (the default) must
        keep its original deferred-to-end, own-byte-boundary treatment -
        only a non-"bit" packFormat changes anything."""
        config = _StubConfig(
            buttons=[_button("b1")],
            sensors=[_laser_banner("banner", laser_count=8, pack_format="bit")],
        )
        mapping = paddng_component(config, sensor_id=["b1", "banner"])
        self.assertEqual(mapping[0], (ByteType.BIT, "b1/sensor_states[0]"))
        self.assertTrue(all(path.startswith("padding_") for _, path in mapping[1:8]))
        self.assertEqual(mapping[8:], [(ByteType.BIT, f"banner/sensor_states[{i}]") for i in range(8)])

    def test_mixed_bit_and_compact_laser_banners_interleave_correctly(self):
        config = _StubConfig(sensors=[
            _laser_banner("bit_banner", laser_count=8, pack_format="bit"),
            _laser_banner("compact_banner", laser_count=16, pack_format="uint16"),
        ])
        mapping = paddng_component(config, sensor_id=["bit_banner", "compact_banner"])
        # Neither is a single bit, so both follow the bits in declaration
        # order - the PLC serializer's rule (generate_st_serde.py: BOOLs
        # first, then every other field as declared): the 8-beam banner is
        # one BYTE, then the uint16 banner one WORD.
        self.assertEqual(mapping[:8], [(ByteType.BIT, f"bit_banner/sensor_states[{i}]") for i in range(8)])
        self.assertEqual(mapping[8:], [(ByteType.UINT16, "compact_banner/sensor_states")])

    def test_compact_field_round_trips_through_a_config_declared_mapping(self):
        """End to end: the mapping comes entirely from config, and the
        resulting ComponentMessage actually works."""
        banner = _laser_banner("banner", laser_count=16, pack_format="uint16")
        config = _StubConfig(sensors=[banner])
        mapping = paddng_component(config, sensor_id=["banner"])
        verify_component_list(mapping, config)
        message = ComponentMessage(mapping)

        banner.sensor_states = "1010101010101010"
        payload = message.serialize(config)
        banner.sensor_states = "0" * 16
        message.deserialize(payload, config)
        self.assertEqual(banner.sensor_states, "1010101010101010")


class RealConfigPackFormatTest(unittest.TestCase):
    """test_fixture_config.json declares sensor_1 (a 32-lamp laser banner) as
    packFormat "uint32" - proves the feature end to end against the real
    fixture, through custom_component_mapping() (what PUBLISH_TOPICS/
    SUBSCRIBE_TOPICS/bootstrap_channel_csv.py actually call)."""

    def test_sensor_1_is_declared_uint32_in_the_real_config(self):
        config = load_config("test_fixture_config.json")
        sensor_1 = next(s for s in config.sensors if s.id == "sensor_1")
        self.assertEqual(sensor_1.packFormat, "uint32")

    def test_custom_component_mapping_emits_one_compact_row_for_sensor_1(self):
        config = load_config("test_fixture_config.json")
        mapping = custom_component_mapping(config, ["sensor_1"])
        self.assertEqual(mapping, [(ByteType.UINT32, "sensor_1/sensor_states")])
        verify_component_list(mapping, config)


if __name__ == "__main__":
    unittest.main()
